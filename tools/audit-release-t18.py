#!/usr/bin/env python3
"""STARFALL T18 release evidence gate; never converts partial test into full pass.

Runs on actual T18 generated JSON, rejecting missing screenshot/telemetry evidence.
This tool does not modify gameplay and deliberately returns RELEASE_CANDIDATE_ONLY
until explicitly provided verified comprehensive independent user mission proof.
"""
import json, math, sys
from pathlib import Path

source=Path(sys.argv[1] if len(sys.argv)>1 else "artifacts/t18-release/release-software-webgl.json")
if not source.is_file():raise SystemExit("T18 EVIDENCE FAIL: browser did not produce release JSON")
data=json.loads(source.read_text(encoding="utf-8"))
checks={}
def require(label,condition):
 checks[label]=bool(condition)
 if not condition:raise SystemExit(f"T18 EVIDENCE FAIL: {label}")
requires=["actualUIOutposts","actualUIWires","pristine","realPower","measuredFieldObservation",
 "workbenchBefore","workbenchAfter","workbenchRestore","durableReload","performance"]
require("all source-owned evidence sections",all(k in data for k in requires))
require("software WebGL explicitly not real GPU",
 "SwiftShader" in data.get("hardware","") and
 "software" in data.get("performance",{}).get("renderer",""))
require("no phantom hardware in untouched game",
 all(data["pristine"].get(k)==0 for k in ["stations","rovers","satellites","photos","packets"]))
parts=data["actualUIOutposts"]
require("eight distinct original UI-built physical structures",
 len(parts)==8 and len({v.get("id") for v in parts})==8 and
 {v.get("kind") for v in parts}=={"battery","solar","connector","lab","hab","storage","antenna","foundation"})
require("seven genuine electrical cable connections",
 len(data["actualUIWires"])==7 and
 all(w.get("connected") and w.get("count")==i+1 for i,w in enumerate(data["actualUIWires"])))
power=data["realPower"]
require("finite actual original power numbers",
 all(isinstance(power.get(k),(int,float)) and math.isfinite(power[k])
 for k in ["batteryJ","batteryCapacityJ","chargedJ","dischargedJ","genW"]))
require("no source charge above capacity",
 0<=power["batteryJ"]<=power["batteryCapacityJ"])
obs=data["measuredFieldObservation"]
require("physical-time paid measured observation identity",
 obs.get("id","").startswith("obs-") and obs.get("bodyId")==power.get("world") and
 isinstance(obs.get("energyJ"),(int,float)) and obs["energyJ"]>0)
before,after,undo=[data[k] for k in ["workbenchBefore","workbenchAfter","workbenchRestore"]]
require("original UI Workbench replacement changes real capacity",
 after.get("part")!=before.get("part") and after.get("capacityJ",0)>before.get("capacityJ",0) and
 after.get("energyJ",1e100)<=before.get("energyJ",-1))
require("rollback uses original hardware and no phantom energy",
 undo.get("part")==before.get("part") and
 undo.get("energyJ",1e100)<=after.get("energyJ",-1) and undo.get("events")==2)
saved=data["durableReload"]
require("all structures and cables remain after durable reload",
 len(saved.get("items",[]))>=8 and saved.get("wires")==7 and
 set(v["id"] for v in parts).issubset(set(saved.get("items",[]))))
require("journal and service IDs survive reload",
 obs["id"] in saved.get("readings",[]) and saved.get("serviceEvents")==2)
require("no invented received image/packet after reload",
 saved.get("noPhantomPhoto") and saved.get("noPhantomPacket"))
p=data["performance"]
require("real observed ordered software-browser frame percentiles",
 p.get("frames")==190 and 0<p.get("p50MS",0)<=p.get("p95MS",0)<=p.get("p99MS",0) and
 all(math.isfinite(p[x]) for x in ["p50MS","p95MS","p99MS"]))
require("zero external network requests or browser exceptions",
 not data.get("externalRequests") and not data.get("pageErrors"))
root=source.parent
require("genuine screenshot files generated by test",
 all((root/x).is_file() and (root/x).stat().st_size>1000 for x in [
  "01-unmodified-spaceflight.png","02-connected-original-outpost.png","03-restored-expedition.png"]))
unverified=[
 "Full original UI-created Planet A + Planet B cross-body photo+lab custody after original rocket insertion",
 "20+ real original UI force-integrated launch to stable orbit",
 "Player-controlled ramp walking, ship reboarding, truck X drive and ruin entry/exit",
 "20-30 minute physical GPU hardware run with frame-time/VRAM/no context loss",
 "Full 100x time-warp active mid-upload plus mid-image downlink interrupted and resumed",
 "Long-run multi-body surface revisit and multiple rover fleet without state/data loss"
]
out={"schema":18,"branch":"feature/t18-end-to-end-release-verification",
 "source":str(source),"decision":"RELEASE_CANDIDATE_ONLY",
 "softwareBrowserChecks":checks,"softwareWebGLMetrics":p,
 "endToEndManualAndFlightBlockers":unverified,"genuineScreenshots":[
  "01-unmodified-spaceflight.png","02-connected-original-outpost.png","03-restored-expedition.png"],
 "doNotMergeMainAutomatically":True}
target=root/"release-gate-verdict.json"
target.write_text(json.dumps(out,indent=2),encoding="utf-8")
print("PASS T18 EVIDENCE CONSISTENCY: only original UI-built physical hardware, energy, science IDs, durable save and observed software frame metrics")
print("RELEASE GATE VERDICT: RELEASE_CANDIDATE_ONLY —",len(unverified),
      "end-to-end/manual/hardware scenarios NOT VERIFIED. Never label complete release.")
