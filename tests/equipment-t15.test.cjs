'use strict';
const assert=require('node:assert/strict');
const M=require('../src/physics/vehicles.js');
const P=require('../src/physics/power.js');
const R=require('../src/physics/rover-dynamics.js');
const T=require('../src/physics/equipment-t15.js');
const ShipOps=require('../src/physics/ship-service-t13.js');
const shStore=M.createStore(),shipOld=shStore.get('ship');
const oldLink=ShipOps.radio({ship:shipOld,report:null});
assert.equal(oldLink.rangeScene,45);
const shipNew=M.clone(shipOld.definition);shipNew.slots.avionics='avionics-ship-long';
assert.equal(M.validate(shipNew).length,0);
const shipUpgrade=shStore.apply('ship',shipNew),shipCurrent=shStore.get('ship');
const newLink=ShipOps.radio({ship:shipCurrent,report:null});
assert(newLink.rangeScene===85&&newLink.bandwidthBps===192000&&newLink.txPowerW===95);
assert(shipCurrent.stats.avionicsW>shipOld.stats.avionicsW);
assert(shipCurrent.stats.massKg>shipOld.stats.massKg);
assert.equal(shipCurrent.state.energyJ,shipOld.state.energyJ,'ship avionics upgrade does not generate electric energy');
const source=M.createStore();
const old=source.get('rover'),id=old.definition.id;
const upgrade=M.clone(old.definition);upgrade.slots.battery='battery-rover-long';
upgrade.slots.solar='solar-rover-large';
upgrade.slots.motor='rover-motor-efficient';
upgrade.slots.wheels='wheels-grippy';
upgrade.slots.instruments='science-suite-rover-geo';
assert.deepEqual(M.validate(upgrade),[]);
const preview=T.validateChange('rover',old,upgrade,true);
assert(preview.after.massKg>preview.before.massKg);
assert(preview.after.batteryCapacityJ>preview.before.batteryCapacityJ);
assert(preview.after.maxSolarW>preview.before.maxSolarW);
assert.notEqual(preview.after.driveTorqueNm,preview.before.driveTorqueNm);
assert.notEqual(preview.after.traction,preview.before.traction);
assert(!M.allowsInstrument(upgrade,'bioassay')&&M.allowsInstrument(upgrade,'magnetometer')&&M.allowsInstrument(upgrade,'seismometer'));
assert(M.allowsInstrument(M.presets.rover,'bioassay')&&M.allowsInstrument(M.presets.rover,'magnetometer'),'original legacy suite must remain backward compatible');
assert.throws(()=>T.validateChange('rover',old,upgrade,false),/interlock/);
assert.throws(()=>T.validateChange('rover',old,old.definition,true),/no installed part/);
assert.throws(()=>T.validateChange('rover',old,{...upgrade,id:'unrelated-rover'},true),/another asset/);
assert.throws(()=>T.validateChange('ship',old,upgrade,true),/same vehicle family/);
assert.throws(()=>T.validateChange('rover',old,upgrade,true,{kind:'7E',runId:'r',blueprintId:'b',sourceAssetId:'somebody-else',sourceDefinitionFingerprint:T.fingerprint(upgrade),observationRefs:[],photoRefs:[]}),/source identity/);
const beforeEnergy=old.state.energyJ;
const real=source.apply('rover',upgrade),next=source.get('rover');
assert(T.changedLive(old,next));assert(next.state.energyJ===beforeEnergy,'larger pack does not grant energy');
assert(real.next.batteryCapacityJ===next.stats.batteryCapacityJ);
assert(next.stats.maxSolarW>old.stats.maxSolarW);
const g={luminosityW:3.828e26,distanceM:149597870700,incidence:.8,transmission:1,occluded:false,ambientK:250};
assert(P.generation(next.stats,g).solarW>P.generation(old.stats,g).solarW);
const ground=()=>0,body={type:'Rocky',id:'star-0-p0',seed:151,radius:2500};
const p={body,local:[0,1,0],forward:[1,0,0],surfaceHeight:ground,sceneRadius:2500,gravityMS2:9.81,command:1,enabled:true};
const oldDrive=R.sixWheels({...p,vehicle:old.stats}),newDrive=R.sixWheels({...p,vehicle:next.stats});
assert(newDrive.maxForceN!==oldDrive.maxForceN||newDrive.friction!==oldDrive.friction,'real six-wheel solver must use new motor/wheel hardware');
assert(T.inspect(next,{draws:{instruments:0},shed:['instruments']},null,'rover').find(x=>x.slot==='instruments').status==='MODELLED','legacy inactive power mode must not claim a served bus');
source.setPower('rover',true);
const powered=source.get('rover');
assert.equal(T.statusFor(powered,'instruments',{draws:{instruments:0},shed:['instruments']}).state,'OUT OF SERVICE');
source.setLoad('rover','instruments',false);
assert.equal(T.statusFor(source.get('rover'),'instruments',null).state,'OUT OF SERVICE');
const faults=T.faults({...powered,state:{...powered.state,energyJ:0,health:.2,temperatureK:450}}, {shed:['avionics']});
assert(faults.some(x=>x.id==='battery')&&faults.some(x=>x.id==='thermal')&&faults.some(x=>x.id==='hull')&&faults.some(x=>x.id==='power-bus'));
let ledger=T.restore(null);
const add=T.append(ledger,'CONFIG_APPLIED',{assetId:id,kind:'rover',timeS:14,
 before:{...old.stats,energyJ:beforeEnergy},after:{...next.stats,energyJ:next.state.energyJ},
 partBefore:old.definition.slots,partAfter:next.definition.slots,
 source:{type:'7E',runId:'run-1',blueprintId:'bp-1',observationRefs:['obs-1'],photoRefs:['photo-1']}});
ledger=add.state;ledger.backup.rover={definition:old.definition,eventId:add.event.id};
const saved=T.restore(JSON.parse(JSON.stringify(ledger)));
assert(saved.backup.rover.definition.slots.wheels===old.definition.slots.wheels);
assert(saved.events[0].source.runId==='run-1'&&saved.events[0].source.photoRefs.includes('photo-1'));
assert(T.inspect(next,null,saved,'rover').find(x=>x.slot==='battery').provenance[0].id===add.event.id);
assert.throws(()=>T.append({...saved,events:Array(500).fill(add.event)},'CONFIG_APPLIED',{assetId:id,kind:'rover',timeS:20}),/full/);
source.apply('rover',saved.backup.rover.definition);
const restored=source.get('rover');
assert.equal(restored.definition.slots.battery,old.definition.slots.battery);
assert.equal(restored.state.energyJ,beforeEnergy,'revert preserves current remaining joules without charging');
assert(M.validate(restored.definition).length===0);
console.log('PASS T15: installed part identity/safety, real six-wheel torque, dynamic T03 radio range and ship electrical load, source-powered solar, finite vehicle charge, actual sensor jobs, persisted provenance/event cap and energy-conserving rollback');
