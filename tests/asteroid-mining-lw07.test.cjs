'use strict';
const assert=require('node:assert/strict');
const Materials=require('../src/physics/material-ledger8a.js');
const Resources=require('../src/physics/planetary-resources8c.js');
const Mining8D=require('../src/physics/mining-hauling8d.js');
const Mining=require('../src/physics/asteroid-mining-lw07.js');
const deposit={id:'8c:1:742:asteroid-A:20:50',bodyId:'asteroid-A',type:'iron_ore',
 grade:.24,accessibleMassKg:100,local:[1,0,0],provenance:'CW01/CW03 asteroid fixture'};
let materials=Mining.prepareContainers(Mining8D.prepareContainers(Materials.create()));
let resources=Resources.create(),model=Mining.create(null,Materials,Resources);
assert.equal(materials.used(Mining.POUCH).massKg,0);
assert.equal(materials.used(Mining.SHIP).massKg,0);
assert.throws(()=>model.start({deposit,surveyed:false,bodyId:'asteroid-A',bodyKind:'asteroid',landed:true,eva:true,operatorNear:true,chargeJ:20000}),/spectrometer/i);
assert.throws(()=>model.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'planet',landed:true,eva:true,operatorNear:true,chargeJ:20000}),/landable asteroid/i);
assert.throws(()=>model.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'asteroid',landed:false,eva:true,operatorNear:true,chargeJ:20000}),/landable asteroid/i);
assert.throws(()=>model.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'asteroid',landed:true,eva:true,operatorNear:true,chargeJ:100}),/9.6 kJ/i);
const task=model.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'asteroid',landed:true,eva:true,operatorNear:true,chargeJ:20000});
assert.equal(task.massKg,2);
assert.equal(task.durationS,12);
assert.throws(()=>model.commit(materials,resources),/incomplete/i);
let used=0;
for(let i=0;i<6;i++){const step=model.advance(2,20000-used,{enabled:true});used+=step.usedJ;}
assert.equal(used,Mining.BATCH.energyJ);
assert.equal(model.active.elapsedS,Mining.BATCH.durationS);
assert.equal(model.advance(2,20000,{enabled:false}).usedJ,0);
const resumed=Mining.create(model.snapshot(),Materials,Resources);
assert.equal(resumed.active.id,task.id);
const committed=resumed.commit(materials,resources);
materials=committed.materials;resources=committed.resources;
assert.equal(materials.used(Mining.POUCH).massKg,2);
assert.equal(materials.used(Mining.SHIP).massKg,0);
assert.equal(resources.remaining(deposit),98);
assert.equal(resources.serialize().transactions[0].provenance,'LW07 EVA asteroid extraction');
assert.equal(materials.inventory(Mining.POUCH)[0].provenance,deposit.id);
assert.equal(resumed.history.at(-1).status,'COMMITTED');
assert.throws(()=>resumed.commit(materials,resources),/incomplete/i);
const savedMaterials=Materials.create(materials.snapshot());
const savedResources=Resources.create(resources.serialize());
const savedMining=Mining.create(resumed.snapshot(),Materials,Resources);
const lot=savedMaterials.inventory(Mining.POUCH)[0];
const moved=savedMining.transfer(savedMaterials,lot.id,2,'lw07:transfer:1');
assert.equal(moved.transfer.status,'COMMITTED');
assert.equal(moved.materials.used(Mining.POUCH).massKg,0);
assert.equal(moved.materials.used(Mining.SHIP).massKg,2);
assert.equal(moved.materials.inventory(Mining.SHIP)[0].provenance,deposit.id);
assert.equal(savedResources.remaining(deposit),98,'Transfer cannot deplete the deposit twice');
assert.throws(()=>savedMining.transfer(moved.materials,lot.id,2,'lw07:transfer:2'),/not in the EVA pouch/i);
const cancelled=Mining.create(null,Materials,Resources);
cancelled.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'asteroid',landed:true,eva:true,operatorNear:true,chargeJ:20000});
assert.equal(cancelled.cancel(),true);
assert.equal(cancelled.active,null);
assert.equal(cancelled.history.at(-1).status,'CANCELLED');
const tiny=Materials.create();
tiny.registerContainer({id:Mining8D.TRUCK,ownerId:'truck-expedition-001',maxMassKg:800,maxVolumeM3:1.2});
tiny.registerContainer({id:Mining8D.SHIP,ownerId:'ship-main',maxMassKg:9000,maxVolumeM3:16});
tiny.registerContainer({id:Mining.POUCH,ownerId:'eva-explorer-001',maxMassKg:1,maxVolumeM3:.0005});
const full=Mining.create(null,Materials,Resources);
full.start({deposit,surveyed:true,bodyId:'asteroid-A',bodyKind:'asteroid',landed:true,eva:true,operatorNear:true,chargeJ:20000});
for(let i=0;i<6;i++)full.advance(2,20000,{enabled:true});
assert.throws(()=>full.commit(tiny,Resources.create()),/pouch is full/i);
assert.equal(tiny.used(Mining.POUCH).massKg,0);
assert.equal(Resources.create().remaining(deposit),100,'Failed capacity check cannot mint or deplete ore');
assert.throws(()=>Mining.create({schema:90}),/Corrupt/i);
console.log('PASS LW07 finite EVA asteroid extraction, survey gate, power debit, pouch custody, physical transfer and save/reload');
