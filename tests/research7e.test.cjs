/* STARFALL 7E — run with: node tests/research7e.test.cjs
   No npm packages. Controlled simulation checks; not real GPU/playthrough proof. */
'use strict';
const assert=require('node:assert/strict');
const V=require('../src/physics/vehicles.js');
require('../src/physics/power.js');
require('../src/physics/science-field.js');
require('../src/physics/rover-dynamics.js');
require('../src/physics/rocket-flight7b.js');
require('../src/physics/launch-systems.js');
const E=require('../src/physics/research7e.js');
const rover=V.clone(V.presets.rover),ship=V.clone(V.presets.ship);
const store=new E.Store();
const close=(a,b,tol=1e-8)=>assert(Math.abs(a-b)<=tol*Math.max(1,Math.abs(b)),a+' != '+b);
const plan=store.plan({type:'rover',title:'Controlled rover slope',definition:rover,world:{bodyId:'rocky-world-42'},conditions:{durationS:60,slopeDeg:6,gearRatio:1,wheelScale:1}});
const run=store.run(plan.id,120),repeat=store.run(plan.id,120);
assert.deepEqual(run.simulated,repeat.simulated,'Identical seeded rover trials must be repeatable');
assert.equal(run.sourceAssetId,rover.id);
assert(run.observationRefs.length===0);
const geared=store.plan({type:'rover',definition:rover,conditions:{durationS:60,slopeDeg:6,gearRatio:3,wheelScale:1}});
const gearedRun=store.run(geared.id,120);
assert.notEqual(run.simulated.distanceM,gearedRun.simulated.distanceM,'Gear ratio must affect travel');
const steep=store.plan({type:'rover',definition:rover,conditions:{slopeDeg:44}});
const steepRun=store.run(steep.id,120);
assert.equal(steepRun.success,false);
assert.throws(()=>store.blueprint(steepRun.id),'Failed test cannot be validated');
const powerPlan=store.plan({type:'power',definition:ship,conditions:{durationS:120,daylight:0,lights:true}});
const powerRun=store.run(powerPlan.id,50);
assert(Number.isFinite(powerRun.simulated.temperatureK));
assert(powerRun.simulated.batteryRemainingJ>=0);
assert(powerRun.simulated.batteryRemainingJ<=V.evaluate(ship).batteryCapacityJ);
const noLights=store.plan({type:'power',definition:ship,conditions:{durationS:120,daylight:0,lights:false}});
const power2=store.run(noLights.id,50);
assert(powerRun.predicted.powerDemandW>=power2.predicted.powerDemandW,'Lights must not save electricity');
const rocketPlan=store.plan({type:'rocket',conditions:{durationS:120,gravityMS2:9.81,rho0:1.1}});
const rocketRun=store.run(rocketPlan.id,50);
assert(Number.isFinite(rocketRun.simulated.maximumAltitudeM));
assert(Number.isFinite(rocketRun.simulated.finalSpeedMS));
assert.equal(rocketRun.success,rocketRun.simulated.stableOrbit&&rocketRun.simulated.phase==='orbit','Suborbital trajectory must never count as insertion');
assert(store.compare(run.id,gearedRun.id).some(x=>x.metric==='distanceM'));
assert.throws(()=>store.compare(run.id,rocketRun.id),'Comparisons must be same experiment type');
const blueprint=store.blueprint(run.id,'Verified rover bench');
assert.equal(blueprint.sourceRunId,run.id);
assert.equal(blueprint.benchOnly,false);
const exported=store.exportBlueprint(blueprint.id),imported=store.importBlueprint(exported);
assert.equal(imported.imported,true);
assert.equal(imported.sourceRunId,run.id);
assert.throws(()=>store.importBlueprint(JSON.stringify({format:'starfall-blueprint-7e',schema:1,blueprint:{}})));
assert.throws(()=>store.importBlueprint('x'.repeat(100001)));
assert.throws(()=>store.plan({type:'rover',definition:ship}));
assert.throws(()=>store.plan({type:'power',definition:ship,conditions:{durationS:Infinity}}));
assert.equal(E.restore({schema:999,plans:[{id:'bad'}]}).plans.length,0);
const roundtrip=new E.Store(store.serialize());assert.deepEqual(roundtrip.serialize(),store.serialize(),'Save roundtrip is lossless');
const preservedOld=new E.Store(null);assert.equal(preservedOld.plans.length,0,'Older save without 7E data is safe');
for(let i=0;i<190;i++)store.run(plan.id,200+i);
assert(store.runs.length<=E.MAX_RUNS,'History is bounded');
close(run.simulated.energyJ,repeat.simulated.energyJ);
console.log('PASS 7E: deterministic model runs, engineering sensitivity, invalid/slope safety, power/heat, actual rocket flight, provenance, blueprint validation, save migration and bounded records');