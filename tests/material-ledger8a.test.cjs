'use strict';
const assert=require('node:assert/strict');
const M=require('../src/physics/material-ledger8a.js');
const m=M.create();
m.registerContainer({id:'ore-hopper',ownerId:'truck-expedition-001',kind:'hopper',maxMassKg:100,maxVolumeM3:1});
m.registerContainer({id:'ship-store',ownerId:'ship-main',kind:'cargo',maxMassKg:75,maxVolumeM3:0.4});
m.importLot({id:'ore-1',materialId:'iron-bearing-ore',containerId:'ore-hopper',massKg:90,volumeM3:0.3,provenance:'test-fixture'});
assert.equal(m.used('ore-hopper').massKg,90);
assert.throws(()=>m.importLot({id:'ore-2',materialId:'ore',containerId:'ore-hopper',massKg:20,volumeM3:0.1,provenance:'test'}),/capacity/);
const a=m.reserve('transfer-a','ore-1','ship-store',60);
assert.equal(a.status,'RESERVED');
assert.deepEqual(m.reserve('transfer-a','ore-1','ship-store',60),a);
assert.throws(()=>m.reserve('transfer-a','ore-1','ship-store',20),/conflict/);
assert.throws(()=>m.reserve('transfer-b','ore-1','ship-store',40),/Insufficient|capacity/);
assert.equal(m.commit('transfer-a').status,'COMMITTED');
assert.equal(m.commit('transfer-a').outputLotId,'transfer:transfer-a');
assert.equal(m.used('ore-hopper').massKg,30);
assert.equal(m.used('ship-store').massKg,60);
assert.equal(m.inventory().reduce((x,l)=>x+l.massKg,0),90,'transfer is mass conserving');
assert.throws(()=>m.cancel('transfer-a'),/Committed/);
const saved=m.snapshot(), restored=M.create(saved);
assert.deepEqual(restored.snapshot(),saved);
assert.equal(restored.commit('transfer-a').outputLotId,'transfer:transfer-a');
const b=restored.reserve('transfer-c','ore-1','ship-store',10);
assert.equal(b.status,'RESERVED');
assert.equal(restored.cancel('transfer-c').status,'CANCELLED');
assert.throws(()=>restored.commit('transfer-c'),/Cancelled/);
assert.equal(restored.inventory().reduce((x,l)=>x+l.massKg,0),90);
assert.throws(()=>M.create({schema:100,containers:[],lots:[],operations:[]}),/Unsupported/);
console.log('Update 8A finite material and transfer tests: PASS');
