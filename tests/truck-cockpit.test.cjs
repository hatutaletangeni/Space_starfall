'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const flight=fs.readFileSync('src/flight.js','utf8');
const cockpit=fs.readFileSync('src/physics/truck-cockpit.js','utf8');
const css=fs.readFileSync('src/physics/truck-cockpit.css','utf8');
const html=fs.readFileSync('index.html','utf8');
const mobile=fs.readFileSync('src/mobile/landscape.html','utf8');
for(const [path,content] of [['src/flight.js',flight],['src/physics/truck-cockpit.js',cockpit]])new (require('node:vm').Script)(content,{filename:path});
assert.match(flight,/if\(landed\)\{if\(eva\|\|truckOccupied\|\|manufacturedOccupied8G\)\{/);
