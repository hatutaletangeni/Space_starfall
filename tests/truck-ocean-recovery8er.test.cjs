'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const Hatch=require('../src/physics/ship-hatch8er.js');
const source=fs.readFileSync('src/flight.js','utf8');
const beacon=fs.readFileSync('src/physics/truck-locator8er.js','utf8');
const css=fs.readFileSync('src/physics/truck-locator8er.css','utf8');
const html=fs.readFileSync('index.html','utf8');
new vm.Script(source,{filename:'src/flight.js'});
new vm.Script(beacon,{filename:'src/physics/truck-locator8er.js'});
assert.ok(html.includes('src/physics/truck-locator8er.js'));
assert.ok(html.includes('src/physics/truck-locator8er.css'));
assert.match(source,/function truckLocator8ER\(\)/);
assert.match(source,/truckHudInfo,truckHudAction,truckLocator8ER,/);
assert.match(source,/const actualLocal=truckBody\?\.id===body\.id&&Array\.isArray\(truckLocal\)\?truckLocal:asset\.location\.local/);
assert.match(source,/Math\.acos\(V\.clamp\(V\.dot\(playerDir,truckDir\),-1,1\)\)/);
assert.match(source,/if\(!landed\|\|nearest\?\.id!==body\.id\)return \{status:'OTHER_WORLD'/);
assert.match(beacon,/FOLLOW ARROW/);
assert.match(beacon,/WATER \/ SHORE/);
assert.match(beacon,/requestAnimationFrame\(tick\)/);
assert.match(css,/body\[data-truck-driving=true\] #sf-truck-locator8er/);
const entry={landed:true,eva:true,truckOccupied:false,swimming:true,rampTransition:null,nearShip:true,walkedSinceExit:6,hatchCooldown:0,atEntrance:true};
assert.equal(Hatch.requestEntry(entry).ok,true,'Surface swimmer can enter correct ship hatch');
assert.equal(Hatch.requestEntry({...entry,atEntrance:false}).ok,false,'No boarding from open ocean');
assert.equal(Hatch.requestEntry({...entry,nearShip:false}).ok,false,'No remote water boarding');
assert.equal(Hatch.requestEntry({...entry,truckOccupied:true}).ok,false,'No car-to-ship instant transfer');
assert.match(source,/const nearWaterline=swimming&&V\.len\(rel\)<24&&Math\.abs\(side\)<15/);
assert.match(source,/groundClearance>=-\.5&&groundClearance<=5/);
assert.match(source,/const maxRelief=\(fromWater\|\|toWater\)/);
assert.match(source,/speed=.*\\*traction\\*\\(shore\\?\\(truckShoreCrawl8ER\\?\\.16:\\.38\\):1\\)/);
assert.match(source,/if\\(action==='SHORE'\\)/);
assert.match(source,/shoreCrawl8er:truckShoreCrawl8ER/);
const cockpit=fs.readFileSync('src/physics/truck-cockpit.js','utf8');
assert.match(cockpit,/data-truck-action="SHORE"/);
assert.match(cockpit,/info.shoreCrawl/);
console.log('PASS: original truck locator, world-scoped arrow, real position, waterline boarding and bounded powered shoreline crawl');
