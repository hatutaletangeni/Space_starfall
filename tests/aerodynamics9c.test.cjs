'use strict';
const assert=require('node:assert/strict');
const A=require('../src/ecology/flight-dynamics9c.js');
const env={pressurePa:100000,temperatureK:290,gravityMS2:9.81,massKg:1.2,sizeM:1};
assert(Math.abs(A.airDensity(101325,293.15)-1.204)<.015,'ideal-gas air density');
assert.equal(A.airDensity(0,293.15),0,'vacuum');
assert.equal(A.airDensity(-1,293.15),0,'negative pressure');
assert.deepEqual(A.start('flier-001',1.2,1,0),A.start('flier-001',1.2,1,0),'seeded startup');
assert.notDeepEqual(A.start('flier-001',1.2,1,0),A.start('flier-002',1.2,1,0),'unique agent');
const initial=A.start('flier-001',1.2,1,0);
const snapshot=structuredClone(initial);
const physics=A.step(initial,env);
assert.deepEqual(initial,snapshot,'step never mutates caller-owned state');
assert(physics.t>initial.t,'clock progresses');
assert(physics.p[1]>0,'physical flyer is above terrain');
assert(physics.wingPhase!==initial.wingPhase,'wing animation responds to active flight');
const vacuum=A.step(initial,{...env,pressurePa:0});
const atmosphere=A.step(initial,env);
assert(atmosphere.v[1]>vacuum.v[1], 'airborne wing lift vs vacuum gravity');
assert(Math.abs(vacuum.v[1]+9.81*A.DT)<1e-8,'vacuum ballistic acceleration');
assert(Math.hypot(...atmosphere.v)<45,'bounded velocity');
const heavy=A.step(initial,{...env,gravityMS2:25});
assert(heavy.v[1]<atmosphere.v[1],'gravity changes flight response');
const lowRho=A.step(initial,{...env,pressurePa:32000});
assert(lowRho.v[1]<atmosphere.v[1],'atmospheric pressure influences lift at same wing speed');
let a=initial,b=initial;
for(let n=0;n<14;n++)a=A.step(a,env);
b=A.advance(b,14*A.DT,env);
assert.deepEqual(b,a,'fixed-step integration independent of frame grouping');
let long=A.start('flight-marathon',2,1.1,0);
for(let i=0;i<12000;i++){long=A.step(long,env);assert(long.p[1]>=1.2-1e-9,'no underground flight');}
assert([...long.p,...long.v,long.bank,long.wingPhase].every(Number.isFinite),'finite long flight');
assert(long.p[1]<300,'flight remains locally bounded in altitude');
assert(Math.hypot(long.p[0],long.p[2])<=75.000001,'bounded local patch');
const fast=A.advance(initial,10000,env);
assert(Number.isFinite(fast.t)&&fast.t===10000,'large time warp is safely bounded');
assert([...fast.p,...fast.v].every(Number.isFinite));
assert.throws(()=>A.step(initial,env,1));
assert.throws(()=>A.advance(initial,-1,env));
console.log('PASS 9C lift/drag/thrust/gravity, seeded flight, bank controller, terrain floor, finite time-warp');
