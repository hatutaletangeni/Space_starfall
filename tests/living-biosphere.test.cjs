'use strict';
const assert=require('node:assert/strict');
// Isolated fixture for existing in-game chemistry and science adapters.
global.StarfallFieldScience={profile:()=>({temperatureK:286,pressurePa:95000,waterIcePotential:.55})};
global.StarfallCompositionCW01={bodyFor:()=>({atmosphereMoleFractions:{O2:.20,N2:.79,CO2:.01}})};
const L=require('../src/ecology/living-biosphere.js');
const body={id:'star-0-p0',kind:'planet',type:'Lush',landable:true,life:true,orbitRadius:100000,systemId:'star-0'};
const site={id:'eco-7nw1',bodyId:body.id,kind:'grazer',group:'fauna',local:[1,0,0]};
const env={light:.85,water:.8,temp:1,oxygen:.21,level:4};
const a=L.seedPatch(site,body,742,null,0),b=L.seedPatch(site,body,742,null,0);
assert.deepEqual(a,b,'repeatable same seeds');
assert(a&&a.plantKg>0);
assert.equal(L.seedPatch({...site,kind:'fossil'},body),null);
const m0=L.mass(a),r=L.advance(a,L.STEP_S*96,env),m1=L.mass(r.state);
assert(Math.abs(m1-m0)<1e-6,'closed parcel mass');
assert(r.state.plantKg>=0&&r.state.oxygenKg>=0&&r.state.carbonDioxideKg>=0);
assert.equal(r.state.stepNo,96);assert.equal(r.state.lastS,L.STEP_S*96);
const r1=L.advance(a,L.STEP_S*42,env).state;
const r2=L.advance(r1,L.STEP_S*96,env).state;
assert.deepEqual(r2,r.state,'fixed steps stable between chunk sizes');
const future=L.advance(a,L.STEP_S*500,env);
assert.equal(future.steps,L.MAX_STEPS);assert(future.pendingS>0,'bounded catchup');
assert.equal(L.advance(future.state,future.state.lastS,env).steps,0);
assert.equal(L.sanitize([r.state,r.state]).length,1);
const bad=structuredClone(r.state);bad.oxygenKg=-1;
assert.equal(L.sanitize([bad]).length,0);
assert.equal(L.world({...body,life:false},742).level,0);
let evolved=r.state;for(let n=0;n<80;n++)evolved=L.advance(evolved,evolved.lastS+L.STEP_S*96,env).state;
assert(Math.abs(L.mass(evolved)-m1)<1e-5,'long term mass balance');
assert(evolved.deaths>=0&&evolved.births>=0);
const aerial={...site,id:'eco-aer9',kind:'flier'};
const winged=L.seedPatch(aerial,body,742,null,0);
assert(winged,'a seedable habitable aerial site must have a food web');
assert.equal(winged.agents.filter(a=>a.role==='flier').length,2,'two independent airborne foragers');
assert(winged.agents.filter(a=>a.role==='flier').every(a=>a.massKg>0&&a.sizeM>0));
const aerialNext=L.advance(winged,L.STEP_S*72,env).state;
assert(Math.abs(L.mass(aerialNext)-L.mass(winged))<1e-6,'winged-feeder local mass conservation');
assert.deepEqual(L.sanitize([aerialNext]),[aerialNext],'new flier roles survive save sanitization');
assert.deepEqual(L.seedPatch(aerial,body,742,null,0),winged,'flight seed stays deterministic');
const bogusFlier=structuredClone(winged);bogusFlier.agents[0].role='unknown';
assert.equal(L.sanitize([bogusFlier]).length,0,'reject arbitrary creature roles');
