'use strict';
const assert=require('node:assert/strict');
require('../src/physics/celestial-composition-cw01.js');
require('../src/terrain/geology-cw03.js');
const Resources=require('../src/physics/planetary-resources8c.js');
const body={id:'stable-planet',kind:'planet',landable:true,type:'Rocky',seed:33};
const frozen={id:'frozen-body',kind:'moon',landable:true,type:'Ice',seed:34};
const airless={id:'airless-body',kind:'moon',landable:true,type:'Rocky',seed:35};
const giant={id:'gas-giant',kind:'planet',landable:false,type:'Gas Giant',seed:36};
assert.equal(Resources.site(giant,[0,1,0],742),null,'No solid ore sites on gas giants');
assert.deepEqual(Resources.tiles([2,2,2]),Resources.tiles([1,1,1]));
assert.deepEqual(Resources.site(body,[1,0,0],742),Resources.site(body,[1,0,0],742));
const existing=Resources.neighbors(body,[.8,.3,.5],742,3);
assert.ok(existing.length>0);
for(const d of existing){
 assert.ok(d.accessibleMassKg>0&&d.grade>=0&&d.grade<=1);
 assert.equal(d.bodyId,body.id);
 assert.deepEqual(Resources.site(body,d.local,742),d,'A site must regenerate from its own center');
}
assert.ok(!Resources.neighbors(airless,[1,0,0],742,4).some(x=>x.type==='carbon_feed'),'Airless rocky world has no fake atmospheric carbon supply');
const ice=Resources.neighbors(frozen,[.4,.8,.2],742,5);
assert.ok(ice.some(x=>x.type==='water_ice'),'Ice body has local water-bearing deposit candidates');
const d=existing[0],store=Resources.create();
assert.equal(store.remaining(d),d.accessibleMassKg);
const report=store.survey(d,120,'EVA field spectrometer');
assert.equal(report.bodyId,body.id);
assert.equal(report.interpretedType,d.type);
assert.ok(!('accessibleMassKg' in report),'Prospecting must not expose the exact modeled reserve');
assert.deepEqual(store.survey(d,999,'EVA field spectrometer'),report,'Re-scan is idempotent');
assert.equal(store.remaining(d),d.accessibleMassKg,'Survey does not mine');
assert.throws(()=>store.extract(d,5,{id:'bad'}),/committed/);
assert.throws(()=>store.extract(d,d.accessibleMassKg+1,{id:'too-big',depositId:d.id,destinationContainerId:'hopper',status:'COMMITTED'}),/depleted/);
const receipt={id:'mine:1',depositId:d.id,destinationContainerId:'hopper',status:'COMMITTED'};
const extraction=store.extract(d,19.5,receipt);
assert.equal(store.remaining(d),d.accessibleMassKg-19.5);
assert.deepEqual(store.extract(d,19.5,receipt),extraction);
assert.throws(()=>store.extract(d,20,{...receipt}),/collision/);
const copy=Resources.create(JSON.parse(JSON.stringify(store.serialize())));
assert.equal(copy.remaining(d),d.accessibleMassKg-19.5);
assert.deepEqual(copy.observations(),[report]);
assert.deepEqual(copy.extract(d,19.5,receipt),extraction);
assert.throws(()=>Resources.create({schema:99,depletions:[],surveys:[],transactions:[]}),/Unsupported/);
assert.notEqual(Resources.site(body,d.local,743)?.id,Resources.site(body,d.local,742)?.id,'Seed changes original world resource provenance');
console.log('8C deterministic finite geology, prospecting and depletion PASS');
