'use strict';
const assert=require('node:assert/strict');
const D=require('../src/physics/debris-lw05.js');
const {generateGalaxy}=require('../src/galaxy.js');
const galaxy=generateGalaxy(742,64);
assert.equal(galaxy.systems.length,2368);
const sys=galaxy.systems.find(s=>s.belts&&s.belts.length),belt=sys?.belts[0];
assert.ok(sys&&belt&&belt.rocks.length>100);
const initial=JSON.stringify(belt.rocks),planet=galaxy.allWorlds.find(b=>b.ring);
assert.ok(planet,'at least one ringed planet');
for(let variant=0;variant<8;variant++){const mesh=D.irregularMesh(variant);
 assert.equal(mesh.triangles,80);assert.equal(mesh.positions.length,mesh.normals.length);
 assert.equal(mesh.indices.length,240);assert.ok(mesh.positions.every(Number.isFinite));
 assert.deepEqual(mesh,D.irregularMesh(variant));}
const first=D.beltRock(sys,belt,belt.rocks[0],0,1234);
assert.equal(first.id,belt.id+':rock:0');assert.ok(first.radius>0);
assert.deepEqual(first,D.beltRock(sys,belt,belt.rocks[0],0,1234));
assert.notDeepEqual(first.position,D.beltRock(sys,belt,belt.rocks[0],0,1244).position);
const ring=D.ringRock(planet,4,4321);assert.equal(ring.kind,'ring-moonlet');
assert.deepEqual(ring,D.ringRock(planet,4,4321));
const rel=ring.position.map((x,i)=>x-planet.position[i]);
const radius=Math.hypot(...rel);
assert.ok(radius>planet.radius*1.32&&radius<planet.radius*planet.ringWidth*1.01);
assert.equal(D.ringRock({...planet,ring:false},0,100),null);
const knownNear=D.nearby(galaxy,first.position,1234,5000);
assert.ok(knownNear.some(x=>x.id===first.id),'nearest real asteroid must be a 3D object');
assert.ok(knownNear.length<=55);
const warning=D.proximity(knownNear,first.position,4);
assert.ok(warning&&warning.collision===true);
const far=D.proximity([first],[...first.position.map(x=>x+1e7)],4);
assert.ok(far.clearance>0&&!far.collision);
assert.equal(JSON.stringify(belt.rocks),initial,'legacy belt source coordinates must not change');
console.log('LW05 star-count, irregular 3D shapes, orbital belt/ring positions and hazards PASS');
