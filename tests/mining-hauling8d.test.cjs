'use strict';
const assert=require('node:assert/strict');
const Materials=require('../src/physics/material-ledger8a.js');
const Resources=require('../src/physics/planetary-resources8c.js');
const Mining=require('../src/physics/mining-hauling8d.js');
const deposit={id:'8c:1:742:worldA:20:50',bodyId:'worldA',type:'iron_ore',grade:.24,
 accessibleMassKg:120,local:[1,0,0],provenance:'verified CW01/CW03 fixture'};
let m=Mining.prepareContainers(Materials.create()),r=Resources.create(),drill=Mining.create(null,Materials,Resources);
assert.equal(m.used(Mining.TRUCK).massKg,0);
assert.equal(m.used(Mining.SHIP).massKg,0);
assert.equal(Mining.prepareContainers(m).containers().length,2);
assert.throws(()=>drill.startDrill({deposit,surveyed:false,bodyId:'worldA',truckBodyId:'worldA',truckPresent:true,operatorNear:true,energyJ:100000}),/survey/i);
assert.throws(()=>drill.startDrill({deposit,surveyed:true,bodyId:'worldB',truckBodyId:'worldA',truckPresent:true,operatorNear:true,energyJ:100000}),/Park truck/);
assert.throws(()=>drill.startDrill({deposit,surveyed:true,bodyId:'worldA',truckBodyId:'worldA',truckPresent:true,operatorNear:true,energyJ:0}),/battery/);
const accepted=drill.startDrill({deposit,surveyed:true,bodyId:'worldA',truckBodyId:'worldA',truckPresent:true,operatorNear:true,energyJ:100000});
assert.equal(accepted.massKg,20);
assert.throws(()=>drill.commit(m,r),/incomplete/);
let consumed=0;
for(let i=0;i<12;i++){const step=drill.advance(2,100000,{enabled:true});consumed+=step.usedJ;}
assert.equal(consumed,Mining.DRILL.minimumEnergyJ);
assert.equal(drill.active.elapsedS,Mining.DRILL.durationS);
const savedTask=drill.snapshot();
const resumed=Mining.create(savedTask,Materials,Resources);
assert.equal(resumed.active.energyJ,consumed);
const committed=resumed.commit(m,r);m=committed.materials;r=committed.resources;
assert.equal(m.used(Mining.TRUCK).massKg,20);
assert.equal(r.remaining(deposit),100);
assert.equal(m.inventory(Mining.TRUCK)[0].provenance,deposit.id);
assert.equal(resumed.receipt(accepted.id).status,'COMMITTED');
assert.throws(()=>resumed.commit(m,r),/incomplete/);
assert.equal(drill.snapshot().active.id,accepted.id,'Original session owner was not silently modified');
let loading=Mining.create(resumed.snapshot(),Materials,Resources);
const ore=m.inventory(Mining.TRUCK)[0];
assert.throws(()=>loading.startLoad({lotId:ore.id,massKg:15,bodyId:'worldA',truckBodyId:'worldA',shipBodyId:'worldB',truckNearShip:true,operatorNear:true,energyJ:100000}),/near landed ship/);
loading.startLoad({lotId:ore.id,massKg:15,bodyId:'worldA',truckBodyId:'worldA',shipBodyId:'worldA',truckNearShip:true,operatorNear:true,energyJ:100000});
let tick=loading.advance(1,100000,{enabled:false});assert.equal(tick.usedJ,0);
for(let i=0;i<8;i++)loading.advance(2,100000,{enabled:true});
const moved=loading.commit(m,r);m=moved.materials;r=moved.resources;
assert.equal(m.used(Mining.TRUCK).massKg,5);
assert.equal(m.used(Mining.SHIP).massKg,15);
assert.equal(r.remaining(deposit),100,'Hauling does not mine any additional resources');
assert.equal(m.inventory().reduce((sum,x)=>sum+x.massKg,0),20);
const again=Mining.create(loading.snapshot(),Materials,Resources);
assert.equal(again.receipt(loading.snapshot().history.at(-1).id).status,'COMMITTED');
assert.equal(Mining.prepareContainers(Materials.create(m.snapshot())).used(Mining.SHIP).massKg,15);
const tiny=Materials.create();tiny.registerContainer({id:Mining.TRUCK,ownerId:'truck-expedition-001',maxMassKg:1,maxVolumeM3:.0001});
tiny.registerContainer({id:Mining.SHIP,ownerId:'ship-main',maxMassKg:9000,maxVolumeM3:16});
const cap=Mining.create(null,Materials,Resources);
cap.startDrill({deposit,surveyed:true,bodyId:'worldA',truckBodyId:'worldA',truckPresent:true,operatorNear:true,energyJ:100000});
for(let i=0;i<12;i++)cap.advance(2,100000,{enabled:true});
assert.throws(()=>cap.commit(tiny,Resources.create()),/capacity/);
assert.equal(tiny.used(Mining.TRUCK).massKg,0,'Failed work never creates ore');
assert.equal(Resources.create().remaining(deposit),120,'Failed work never depletes deposit');
assert.equal(cap.active.type,'DRILL','Failed commit may be retried after correcting capacity');
assert.throws(()=>Mining.create({schema:200}),/Corrupt/);
console.log('PASS 8D finite powered drilling, transfer, depletion, capacity rollback, save/reload and conservation');
