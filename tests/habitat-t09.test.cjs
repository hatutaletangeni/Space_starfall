'use strict';
const assert=require('node:assert/strict');
const O=require('../src/physics/outposts.js');
const P=require('../src/physics/power-ledger-t02.js');
const H=require('../src/physics/habitat-t09.js');
const body={id:'earth-like-p0',systemId:'earth-like',position:[0,0,0],
 radius:6200,gravity:1,landable:true,kind:'planet',spinAxis:[0,1,0],spinAngle:0,
 spinPeriod:86400,surfaceTemperatureK:230,surfacePressureKPa:0};
const hab={id:'hab-1',kind:'hab',bodyId:body.id,local:[1,0,0],enabled:true,condition:1};
const original=H.ensure(hab,0);
assert.equal(original.schema,1);assert.equal(original.enabled,false);
assert.equal(H.inspect(hab,body,false).state,'STANDBY');
assert(H.inspect(hab,body).oxygenKPa>20);
assert.throws(()=>H.command(hab,'ENABLE',{near:false}),/approaching/);
H.command(hab,'ENABLE',{near:true,now:0,body});
H.step(hab,body,600,true);
let working=H.inspect(hab,body,true);
assert.equal(working.state,'PRESSURIZED',JSON.stringify(working));
assert.equal(working.watts,680);
assert(working.pressureKPa>70);
assert(working.oxygenTankMol<1050&&working.inertTankMol<3500);
const tank=working.oxygenTankMol,inert=working.inertTankMol,water=working.waterL;
H.command(hab,'OCCUPANCY',{near:true,occupants:2,now:600,body});
H.step(hab,body,1800,true);
working=H.inspect(hab,body,true);
assert(working.waterL<water);
assert(working.oxygenTankMol<tank);
assert(working.inertTankMol<inert);
assert(working.carbonKPa<.8,'real finite scrubber must control low crew CO2');
assert(H.ensure(hab).filteredAirMol>0);
H.command(hab,'CYCLE_OUT',{near:true,powered:true,now:1800,body});
assert.equal(H.inspect(hab,body,true).airlock,'CYCLING_OUT');
H.step(hab,body,1810,true);assert.equal(H.inspect(hab,body,true).airlock,'CYCLING_OUT');
H.step(hab,body,1820,true);assert.equal(H.inspect(hab,body,true).airlock,'OPEN_OUT');
H.command(hab,'CYCLE_IN',{near:true,powered:true,now:1820,body});
H.step(hab,body,1840,true);assert.equal(H.inspect(hab,body,true).airlock,'CLOSED');
assert.throws(()=>H.command(hab,'CYCLE_OUT',{near:true,powered:false,now:1840,body}),/Powered/);
// Blackout isolates active HVAC; gas leak and external heat sink remain physical.
hab.habT09.seal=.32;
const before=H.inspect(hab,body,true),inventory={
 oxygen:before.oxygenTankMol,inert:before.inertTankMol,
 scrubber:before.scrubberCapacityMol,water:before.waterL};
H.step(hab,body,3640,false);
const after=H.inspect(hab,body,false);
assert(after.pressureKPa<before.pressureKPa*.4,'damaged seal must physically depressurize without DC');
assert(after.oxygenTankMol===inventory.oxygen&&after.inertTankMol===inventory.inert);
assert(after.scrubberCapacityMol===inventory.scrubber);
assert(after.waterL<=inventory.water);
assert(after.temperatureK<before.temperatureK);
assert(after.alarms.includes('PRESSURE_UNSAFE')&&after.alarms.includes('LEAK'));
assert.equal(after.state,'LEAK');
assert.throws(()=>H.command(hab,'CYCLE_OUT',{near:true,powered:true,now:3640,body}),/HABITAT_UNSAFE/);
assert.throws(()=>H.command(hab,'REPAIR',{near:false,now:3640,body}),/approaching/);
H.command(hab,'REPAIR',{near:true,now:3640,body});
assert.equal(H.inspect(hab,body,true).seal,1);
const low=H.inspect(hab,body,true);
assert(low.pressureKPa<70,'repair must not create gas');
H.step(hab,body,4000,true);
const restored=H.inspect(hab,body,true);
assert(restored.pressureKPa>low.pressureKPa,'finite O2/inert reserve restores pressure gradually');
assert(restored.oxygenTankMol<low.oxygenTankMol||restored.inertTankMol<low.inertTankMol);
assert.throws(()=>H.command(hab,'CYCLE_OUT',{near:true,powered:true,now:4000,body}),/UNSAFE/);
const saved=JSON.parse(JSON.stringify(hab));
const clone={...saved,habT09:JSON.parse(JSON.stringify(saved.habT09))};
assert.equal(H.ensure(clone).lastS,4000);
assert(Math.abs(H.inspect(clone,body,true).oxygenKPa-restored.oxygenKPa)<1e-6);
const beforeRepeat=H.inspect(clone,body,true).oxygenTankMol;
H.step(clone,body,4000,true);
assert.equal(H.inspect(clone,body,true).oxygenTankMol,beforeRepeat,'repeat same mission tick does not consume twice');
const initialNew={kind:'hab',id:'old-hab',bodyId:body.id};
assert.equal(H.ensure(initialNew,500).enabled,false);
assert.equal(H.ensure(initialNew,700).lastS,500,'legacy migration only once');
const actualStore=new O.Store(742);
actualStore.items.push(JSON.parse(JSON.stringify(clone)));
const restoredStore=new O.Store(742,actualStore.serialize());
const restoredHab=restoredStore.items.find(x=>x.id===clone.id);
assert(restoredHab,'original outpost5 Store must keep habitat with its nested T09 record');
assert.equal(restoredHab.habT09.schema,1);
assert(Math.abs(restoredHab.habT09.oxygenTankMol-clone.habT09.oxygenTankMol)<1e-6);
const oldStore=new O.Store(742,{schema:1,seed:742,serial:1,items:[{id:'old-hab',kind:'hab',bodyId:body.id,
  local:[1,0,0],facing:[0,1,0],condition:1,enabled:true}],wires:[]});
assert(oldStore.items.length===1&&oldStore.items[0].habT09.enabled===false);
const long={kind:'hab',id:'long',bodyId:body.id};H.ensure(long,0);
long.habT09.enabled=true;
H.step(long,body,90000,true);
assert(H.inspect(long,body,true).alarms.includes('AWAITING_REVIEW'));
assert.equal(H.inspect(long,body,true).oxygenTankMol,1050,'no overlong time skip energy or air production');
// Mid-cycle blackout must pause the actual powered door motor; a leak must
// abort an unsafe outward transition, without a fake open door.
const lock={id:'airlock-test',kind:'hab',bodyId:body.id,enabled:true,condition:1};
H.ensure(lock,0);H.command(lock,'ENABLE',{near:true,now:0,body});
H.step(lock,body,1,true);
H.command(lock,'CYCLE_OUT',{near:true,powered:true,now:1,body});
H.step(lock,body,20,false);
assert.equal(H.inspect(lock,body,false).airlock,'CYCLING_OUT','DC blackout pauses powered actuator');
H.step(lock,body,30,true);
assert.equal(H.inspect(lock,body,true).airlock,'CYCLING_OUT','remaining motor time not silently completed');
lock.habT09.seal=.1;
H.step(lock,body,35,true);
assert.equal(H.inspect(lock,body,true).airlock,'CLOSED','dangerous leak aborts outward transition');
assert(H.inspect(lock,body,true).alarms.includes('LEAK'));
const serviceHab={id:'hab-service',kind:'hab',bodyId:body.id,enabled:true,condition:1,local:[1,0,0]};
H.ensure(serviceHab,0);H.command(serviceHab,'ENABLE',{near:true,now:0,body});
H.step(serviceHab,body,30,true);
const battery={id:'battery-1',kind:'battery',bodyId:body.id,energyJ:5e6,enabled:true,condition:1};
const rover={id:'rover-1',bodyId:body.id,local:[1,0,0],batteryJ:2e6,capacityJ:14.4e6};
const store={connectedGroups:()=>[[serviceHab,battery]]};
const preJ=battery.energyJ+rover.batteryJ;
const res=H.serviceRover(serviceHab,rover,store,body,30,30,true);
assert(res.drawnJ>res.deliveredJ&&res.lossJ>0);
assert.equal(preJ-(battery.energyJ+rover.batteryJ),res.lossJ);
assert.throws(()=>H.serviceRover(serviceHab,rover,store,body,30,30,true),/cooling/);
const far={...rover,id:'far',local:[-1,0,0]};
assert.throws(()=>H.serviceRover(serviceHab,far,store,body,90,30,true),/out of range/);
assert(H.inspect(serviceHab,body,true).serviceReady);
console.log('PASS T09: finite ideal-gas O2/inert/carbon/H2O, powered HVAC and leak blackout, pressure-guarded airlock, saved state/clock, explicit repair, source-debited T02 charging and no survival damage');
