'use strict';
const assert=require('node:assert/strict');
global.StarfallCompositionCW01=require('../src/physics/celestial-composition-cw01.js');
global.StarfallStableTerrain=require('../src/terrain/stable-surface.js');
global.StarfallFieldScience=require('../src/physics/science-field.js');
global.StarfallMeteorologyLW03=require('../src/physics/meteorology-lw03.js');
const H=global.StarfallHydrosphereLW04=require('../src/physics/hydrosphere-lw04.js');
const Mesh=require('../src/terrain/water-mesh-lw04.js');
const {generateGalaxy}=require('../src/galaxy.js');
const galaxy=generateGalaxy(742,64);
assert.equal(galaxy.systems.length,2368);
const ocean=galaxy.allWorlds.find(x=>x.type==='Ocean'&&x.kind==='planet'),rock=galaxy.allWorlds.find(x=>x.type==='Rocky'&&x.kind==='planet');
assert.ok(ocean&&rock);
assert.ok(H.material(ocean,742)&&H.material(ocean,742).densityKgM3>=998);
assert.equal(H.material(rock,742),null);
const unit=[.6,.8,0],t=14567.12;
const a=H.wave(ocean,unit,t,742),b=H.wave(ocean,unit,t,742);
assert.equal(a,b);assert.ok(Math.abs(a)<.01,'wave amplitude bounded');
const windy=H.wave(ocean,unit,t,742,{windMS:80}),still=H.wave(ocean,unit,t,742,{windMS:1});
assert.notEqual(windy,still);
global.Starfall3D={field:()=>.4,groundHeight:()=>0};
const bathymetry=H.sample(ocean,unit,0,t,742);
assert.equal(bathymetry.hasWater,true);
assert.equal(bathymetry.submerged,true);
assert.ok(bathymetry.depthM>1000);
assert.ok(bathymetry.pressurePa>1e7);
const floating=H.buoyancy(bathymetry,.12,105,.016),sinking=H.buoyancy(bathymetry,.05,105,.016);
assert.ok(floating.upthrustN>floating.weightN);
assert.ok(sinking.upthrustN<sinking.weightN);
const tile=global.StarfallStableTerrain.descriptorForDirection(ocean,unit);
const sea=Mesh.geometry(ocean,tile,18,()=>.4,()=>0);
assert.ok(sea&&sea.triangles>0);
assert.equal(sea.indices.length/3,sea.triangles);
assert.ok(sea.positions.every(Number.isFinite));
assert.deepEqual(sea,Mesh.geometry(ocean,tile,18,()=>.4,()=>0));
assert.equal(Mesh.geometry(ocean,tile,18,()=>.9,()=>40),null);
assert.equal(Mesh.geometry(rock,tile,18,()=>.4,()=>0),null);
global.Starfall3D={field:()=>.9,groundHeight:()=>40};
assert.equal(H.sample(ocean,unit,40,t,742).hasWater,false,'dry coast must not become water');
delete global.Starfall3D;
assert.throws(()=>H.wave(ocean,unit,-2,742));
assert.throws(()=>H.buoyancy(bathymetry,-1,100,.2));
console.log('LW04 2368 stars; deterministic waves, water meshes, dry land, depth and Archimedes PASS');
