'use strict';
const assert=require('node:assert/strict');
const Cargo=require('../src/physics/cargo-bay8b.js');
const Inventory=require('../src/physics/physical-inventory8a.js');
const Custody=require('../src/physics/truck-custody8b.js');
const stock=Inventory.create(),truckId='truck-expedition-001';
const saved=JSON.stringify(stock.serialize()),truck=stock.get(truckId);
assert.equal(truck.location.kind,'ship');
const groundFlag=Custody.restore({schema:1,mode:'ground',pose:{x:16.5,z:39,y:-7.25},counter:2},truck,null);
assert.equal(groundFlag.issue,'REPAIRED');
assert.equal(groundFlag.cargo.mode,'secured');
assert.equal(groundFlag.cargo.pose.z,5.7);
assert.match(Custody.description(truck,groundFlag.cargo,null),/SECURED INSIDE SHIP/);
assert.equal(JSON.stringify(stock.serialize()),saved,'reconcile never edits physical assets');
const staleRamp=Custody.restore({schema:1,mode:'ramp',pose:{x:16.5,z:30,y:-4},counter:3},truck,'planet-A');
assert.equal(staleRamp.cargo.mode,'secured');
assert.equal(staleRamp.cargo.counter,3);
const moved=stock.move(truckId,{kind:'surface',bodyId:'planet-A',local:[0,1,0]},'test:release');
assert.equal(moved.status,'COMMITTED');
const surface=stock.get(truckId);
const securedFlag=Custody.restore({schema:1,mode:'secured',pose:{x:16.5,z:5.7,y:-1.2},counter:3},surface,'planet-A');
assert.equal(securedFlag.cargo.mode,'ground');
assert.match(Custody.description(surface,securedFlag.cargo,'planet-B'),/DIFFERENT WORLD/);
const resume=Custody.restore({schema:1,mode:'ramp',pose:{x:16.5,z:15,y:-1.2},counter:4},surface,'planet-A');
assert.equal(resume.cargo.mode,'ramp');
const remoteRamp=Custody.restore(resume.cargo,surface,'planet-B');
assert.equal(remoteRamp.cargo.mode,'ground');
const beforeMissing=JSON.stringify(stock.serialize());
const missing=Custody.restore(null,null,'planet-A');
assert.equal(missing.issue,'MISSING');
assert.match(Custody.description(null,missing.cargo,'planet-A'),/MISSING/);
assert.equal(JSON.stringify(stock.serialize()),beforeMissing);
assert.equal(stock.list().filter(x=>x.id===truckId).length,1);
const roundTrip=Inventory.create(stock.serialize());
assert.deepEqual(roundTrip.get(truckId).location,surface.location);
console.log('PASS 8B original truck custody: ship/ramp/remote/missing flags reconcile without moving or duplicating a single vehicle');
