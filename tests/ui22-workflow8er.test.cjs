'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const index=read('index.html'),workflow=read('src/ui22-workflow.js'),style=read('src/ui22-workflow.css');
const mobile=read('src/mobile/landscape.html'),adapter=read('src/mobile/landscape.js');
const truck=read('src/physics/truck-cockpit.js'),truckCss=read('src/physics/truck-cockpit.css');
for(const [path,code] of [['ui22',workflow],['mobile adapter',adapter],['truck HUD',truck]])new vm.Script(code,{filename:path});
assert.match(index,/src\/ui22-workflow\.css/);
assert.match(index,/src\/ui22-workflow\.js/);
assert.ok(index.indexOf('src/ui22-workflow.js')>index.indexOf('src/ui21.js'),'Workflow must enhance existing page navigation');
for(const [i,name] of ['Navigate','Explore','Build','Operate','Records'].entries())assert.match(workflow,new RegExp("name:'"+name+"'"));
assert.ok(workflow.indexOf("name:'Navigate'")<workflow.indexOf("name:'Records'"));
assert.match(workflow,/target\.click\(\)/); // native action ownership retained
assert.match(workflow,/target\.click\(\)/);
assert.match(workflow,/StarfallWorkflow8ER/);
assert.match(style,/#ui21-navigation\{display:none!important\}/);
assert.match(style,/#sf-quick-tools\{display:none!important\}/);
assert.match(style,/data-sf-view="eva"/);
assert.match(style,/data-sf-view="ship-interior"/);
for(const action of ['mission','map','save','hide'])assert.ok(mobile.includes('data-mobile-action="'+action+'"'));
for(const removed of ['menu','engineer','tools'])assert.ok(!mobile.includes('data-mobile-action="'+removed+'"'));
assert.match(adapter,/mission:\(\)=>window\.StarfallWorkflow8ER\?\.toggle\(\)/);
assert.match(mobile,/data-control="KeyW"/);
assert.match(mobile,/data-control="KeyS"/);
assert.match(mobile,/data-mobile-key="KeyX"/);
assert.match(mobile,/data-mobile-key="KeyI"/);
for(const a of ['EXIT','MAP','VIEW','LIGHTS','SHORE','MINE','LOAD','CANCEL'])assert.ok(truck.includes('data-truck-action="'+a+'"'),'Truck action '+a+' must still exist');
assert.ok(truck.includes('<details class="sft-section">'),'Complex truck systems must be grouped');
assert.ok(truck.indexOf('data-truck-action="EXIT"')<truck.indexOf('<details'),'Exit must be immediate');
assert.match(truckCss,/sft-main-actions/);
console.log('PASS: UI22 chronological workflow, preserved actions, mobile context and reduced truck HUD');
