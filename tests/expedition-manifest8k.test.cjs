'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
globalThis.StarfallMaterials8A=require('../src/physics/material-ledger8a.js');
globalThis.StarfallPhysical8A=require('../src/physics/physical-inventory8a.js');
globalThis.StarfallMining8D=require('../src/physics/mining-hauling8d.js');
globalThis.StarfallIndustrialSite8E=require('../src/physics/industrial-site8e.js');
globalThis.StarfallMachineInstall8F=require('../src/physics/machine-install8f.js');
const M=require('../src/physics/expedition-manifest8k.js');
const fresh=()=>globalThis.StarfallMining8D.prepareContainers(globalThis.StarfallMaterials8A.create());
const newer=M.initialize({freshExpedition:{schema:1,seed:742,startedAt:1},credits:200},fresh());
assert.equal(newer.seeded,false,'Explicit newer 8K manifest owns fresh-expedition stock: older bootstrap cannot duplicate it');
assert.equal(newer.materials.inventory().length,0);
const receipted=M.initialize({initialIndustrialManifest8k:{status:'COMMITTED'},credits:200},fresh());
assert.equal(receipted.seeded,false,'Existing receipt-owned 8K manifest must never be topped up by legacy bootstrap');
assert.equal(receipted.materials.inventory().length,0);
const first=M.initialize({version:2,credits:200,discoveries:[]},fresh());
assert.equal(first.seeded,true,'Brand-new seed may carry ONE finite pre-existing manifest');
const src=first.materials.snapshot(),lots=first.materials.inventory(M.HOLD),sum=M.summary();
assert.equal(lots.length,sum.entries);
assert.ok(sum.massKg>1000&&sum.massKg<9000);
assert.ok(sum.volumeM3>0&&sum.volumeM3<=16,'Ship hold must fit all packed hardware');
assert.ok(Math.abs(first.materials.used(M.HOLD).massKg-sum.massKg)<1e-8);
assert.ok(Math.abs(first.materials.used(M.HOLD).volumeM3-sum.volumeM3)<1e-8);
assert.equal(new Set(lots.map(x=>x.id)).size,lots.length,'Stable source-owned IDs');
assert.ok(lots.every(x=>x.provenance==='initial_manifest:v1:preflight_industrial_supply'));
assert.ok(lots.every(x=>x.grade>=.98));
const kit=lots.find(x=>x.materialId==='plant_kit_air_fractionation');
assert.equal(kit.massKg,globalThis.StarfallIndustrialSite8E.KITS.plant_kit_air_fractionation.massKg);
assert.ok(lots.some(x=>x.materialId==='stocked_chips'),'Non-native semiconductor bootstrap must be finite imported stock');
assert.equal(lots.find(x=>x.materialId==='stocked_chips').massKg,.1);
// Saved manifest or old flight must NEVER get a second lot or another free starter kit.
const reload=M.initialize({materials8a:src,flightGalaxy:{seed:742}},globalThis.StarfallMaterials8A.create(src));
assert.equal(reload.seeded,false);
assert.deepEqual(reload.materials.snapshot(),src);
const old=M.initialize({flightGalaxy:{seed:742},credits:25,discoveries:[{id:'old'}]},fresh());
assert.equal(old.seeded,false,'Legacy industrial pre-8A save must not get silently enriched');
assert.equal(old.materials.inventory().length,0);
const oldWithAssets=M.initialize({physical8a:{schema:1,assets:[]}},fresh());
assert.equal(oldWithAssets.seeded,false);
const damaged=fresh(),invalid=damaged.snapshot();invalid.containers.find(c=>c.id===M.HOLD).maxVolumeM3=3;
assert.throws(()=>M.initialize({freshExpedition:{seed:742}},globalThis.StarfallMaterials8A.create(invalid)),/does not fit/);
assert.equal(globalThis.StarfallPhysical8A.create().list().filter(x=>x.id==='truck-expedition-001').length,1);
const flight=fs.readFileSync('src/flight.js','utf8'),index=fs.readFileSync('index.html','utf8');
assert.match(flight,/StarfallExpeditionManifest8K\.initialize\(session/);
assert.ok(index.indexOf('src/physics/expedition-manifest8k.js')<index.indexOf('src/flight.js'));
console.log('PASS 8K finite certified preflight kit BOM, original ship 16m3/9000kg, one-time immutable IDs, old-save preservation, no per-landing grant');
