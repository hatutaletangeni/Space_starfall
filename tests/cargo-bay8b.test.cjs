'use strict';
const assert=require('node:assert/strict');
const Cargo=require('../src/physics/cargo-bay8b.js');
const Inventory=require('../src/physics/physical-inventory8a.js');
const bay=Cargo.BAY;
const stock=Inventory.create();
const truck=stock.get('truck-expedition-001');
assert.equal(Cargo.fit(truck).ok,true);
assert.equal(bay.vehicleWidth+2*bay.clearanceMargin<bay.maxX-bay.minX,true);
assert.equal(Cargo.canApproach({x:bay.centerX,z:bay.rampEndZ+3,y:-7},-.9),true);
assert.equal(Cargo.canApproach({x:2,z:bay.rampEndZ+3,y:-7},-.9),false);
assert.equal(Cargo.canApproach({x:bay.centerX,z:bay.rampEndZ+3,y:-7},.9),false);
assert.throws(()=>Cargo.advance({x:0,z:31,y:0},1),/clearance/);
let p={x:bay.centerX,z:bay.rampEndZ,y:Cargo.height(bay.rampEndZ)};
let step=0;
while(p.z>11.5&&step++<100){p=Cargo.advance(p,1);}
assert.ok(p.inside);
assert.ok(Math.abs(p.y-bay.floorY)<1e-8);
const deployed=stock.move(truck.id,{kind:'surface',bodyId:'planet-A',local:[0,1,0]},'unsecure:1');
assert.equal(deployed.status,'COMMITTED');
const locked=stock.move(truck.id,{kind:'ship',slot:'starboard-hangar'},'secure:2',{expected:deployed.destination,maxMassKg:bay.maxCargoMassKg,maxVolumeM3:bay.maxCargoVolumeM3});
assert.equal(locked.status,'COMMITTED');
assert.equal(stock.get(truck.id).location.kind,'ship');
assert.equal(stock.list().filter(a=>a.type==='truck').length,1);
assert.deepEqual(Inventory.create(stock.serialize()).get(truck.id).location,stock.get(truck.id).location);
assert.throws(()=>stock.move(truck.id,{kind:'surface',bodyId:'planet-B',local:[0,0,1]},'secure:2'),/Transfer ID already used/);
assert.throws(()=>Cargo.snapshot({schema:1,mode:'secured',pose:{x:NaN,y:0,z:0},counter:0}),/Invalid/);
assert.equal(Cargo.snapshot(Cargo.snapshot()).mode,'secured');
const advice=(mode,pos,heading)=>Cargo.loadingAdvice(mode,pos,heading);
assert.match(advice('secured',null,0),/ALREADY SECURED/);
assert.match(advice('ramp',{x:bay.centerX,z:19,y:Cargo.height(19)},-.9),/STILL ON RAMP/);
assert.match(advice('ramp',{x:bay.centerX,z:11.2,y:Cargo.height(11.2)},-.9),/fully on cargo deck/);
assert.match(advice('ground',{x:0,z:bay.rampEndZ+3,y:0},-.9),/OFF-CENTER/);
assert.match(advice('ground',{x:bay.centerX,z:bay.rampEndZ+15,y:0},-.9),/from BEHIND/);
assert.match(advice('ground',{x:bay.centerX,z:bay.rampEndZ+3,y:0},.9),/wrong way/);
assert.match(advice('ground',{x:bay.centerX,z:bay.rampEndZ+3,y:0},-.9),/correctly aligned/);
assert.equal(Cargo.snapshot().mode,'secured');
assert.equal(Cargo.canApproach({x:bay.centerX,z:bay.rampEndZ+3,y:-7},-.9),true);
console.log('8B geometry + cargo custody invariants PASS');
