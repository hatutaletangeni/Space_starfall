'use strict';
const assert=require('node:assert/strict');
const Impacts=require('../src/physics/asteroid-impacts-lw07.js');
const body={id:'system-A-p0',kind:'planet',type:'Rocky',radius:1200,seed:42};
const system={id:'system-A',belts:[{id:'system-A-belt0',rocks:Array.from({length:420},(_,i)=>i)}],bodies:[body]};
const noBelt={id:'system-B',belts:[]};
const untouched={id:'system-B-p0',kind:'planet',type:'Rocky',radius:900,seed:77};
const shattered={id:'system-B-p1',kind:'moon',type:'Shattered',radius:400,seed:78};
assert.equal(Impacts.staticCraters(untouched,noBelt,742).length,0,'No asteroid belt means no asteroid-impact scars');
assert.ok(Impacts.staticCraters(shattered,noBelt,742).length>=5,'Shattered body retains fragmentation scars');
const original=JSON.stringify(system.belts);
const a=Impacts.staticCraters(body,system,742),b=Impacts.staticCraters(body,system,742);
assert.ok(a.length>0);assert.deepEqual(a,b,'Historic crater field is deterministic');
assert.ok(a.every(x=>x.radiusScene>0&&x.depthScene>0&&Math.abs(Math.hypot(...x.direction)-1)<1e-8));
Impacts.attachSystem(system,742);
assert.equal(body.impactCraters.length,a.length);
assert.equal(body.impactRevision,1);
let event=null;
for(let w=0;w<10000&&!event;w++)event=Impacts.scheduled(body,system,w,742);
assert.ok(event,'Belt-bearing system should produce occasional deterministic impact windows');
const store=Impacts.create();
assert.equal(store.step(body,system,event.impactTimeS-9,742),null);
const active=store.step(body,system,event.impactTimeS-7,742);
assert.ok(active&&active.id===event.id&&active.phase>0);
assert.equal(store.craterCount,0,'Crater is not created before impact');
const before=body.impactCraters.length;
store.step(body,system,event.impactTimeS+1,742);
assert.equal(store.craterCount,1);
assert.equal(body.impactCraters.length,before+1,'Impact leaves a permanent crater');
assert.ok(body.impactRevision>1,'Surface mesh invalidation revision advances');
assert.equal(store.step(body,system,event.impactTimeS+8,742),null,'Impact visual is transient');
const restored=Impacts.create(JSON.parse(JSON.stringify(store.serialize())));
const revisited={...body,impactBaseCraters:body.impactBaseCraters,impactCraters:body.impactBaseCraters,impactRevision:1};
restored.step(revisited,system,event.impactTimeS+20,742);
assert.equal(revisited.impactCraters.length,before+1,'Crater persists after save/reload and revisit');
assert.equal(Impacts.scheduled(untouched,noBelt,0,742),null);
assert.equal(JSON.stringify(system.belts),original,'Impact simulation cannot mutate asteroid source population');
console.log('PASS LW07 seeded belt-dependent impacts, closed crater records, persistence and no-belt exclusion');
