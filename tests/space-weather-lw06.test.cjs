'use strict';
const assert=require('node:assert/strict');
const G=require('../src/galaxy.js'),W=require('../src/physics/space-weather-lw06.js');
const galaxy=G.generateGalaxy(742,64);
assert.equal(galaxy.systems.length,2368);
const system=galaxy.systems.find(x=>x.phenomenon==='supernova');
const pulsar=galaxy.systems.find(x=>x.phenomenon==='pulsar');
assert.ok(system&&pulsar,'existing seed must contain physically tagged stellar sources');
const old=JSON.stringify([system.position,system.star,system.phenomenon,system.nebulae,system.belts]);
const src=W.source(system,742),rem=W.remnant(src,50),future=W.remnant(src,150);
assert.equal(src.kind,'supernova-remnant');assert.equal(rem.id,future.id);
assert.ok(future.radiusScene>rem.radiusScene&&future.dustFraction>=rem.dustFraction);
assert.ok(rem.gasFraction+rem.dustFraction===1);
assert.deepEqual(rem,W.remnant(src,50));assert.equal(W.remnant(W.source(pulsar),50),null);
const cloud=system.nebulae.map(x=>x.id);
assert.deepEqual(system.nebulae.map(x=>x.id),cloud,'pre-existing molecular clouds remain distinct');
const shell=W.remnantParticles(system,50,90,742);
assert.equal(shell.length,90);assert.ok(shell.every(x=>x.position.every(Number.isFinite)&&x.alpha>=0));
assert.deepEqual(shell,W.remnantParticles(system,50,90,742));
const nearestOrbit=[system.position[0]+system.star.radius*2,system.position[1],system.position[2]],farOrbit=[system.position[0]+system.star.radius*600,system.position[1],system.position[2]];
const exposure=W.exposure(system,nearestOrbit,400,742),far=W.exposure(system,farOrbit,400,742);
assert.ok(exposure.ionizationIndex>=0&&exposure.ionizationIndex<=1&&far.ionizationIndex<=1);
assert.ok(exposure.solarTransmissionFactor<=1&&exposure.solarTransmissionFactor>=.22);
assert.deepEqual(exposure,W.exposure(system,nearestOrbit,400,742));
assert.ok(W.source(pulsar).kind==='pulsar');
const flareSrc=W.source(pulsar),peak=flareSrc.cycleS-flareSrc.epochS+flareSrc.durationS/2;
const local=W.flare(flareSrc,peak,0);
const delayed=W.flare(flareSrc,peak+W.C_SCENE_S*4/W.C_SCENE_S, W.C_SCENE_S*4);
assert.ok(local.flareStrength>.99&&delayed.flareStrength>.99);
assert.equal(delayed.lightTravelDelayS,4);
assert.ok(W.exposure(pulsar,farOrbit,1e5,742).ionizationIndex>=0);
assert.equal(JSON.stringify([system.position,system.star,system.phenomenon,system.nebulae,system.belts]),old);
assert.throws(()=>W.remnant(src,-1));
assert.throws(()=>W.flare(src,-1));
console.log('LW06 real seed 742: 2368 stars, source-linked remnant expansion, pulse propagation and unchanged catalog PASS');
