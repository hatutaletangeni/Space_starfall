'use strict';
const assert=require('node:assert/strict');
const Galaxy=require('../src/galaxy.js');
const Nav=require('../src/physics/truck-navigation8b.js');
const galaxy=Galaxy.generateGalaxy(742,64);
const truck={id:'truck-expedition-001',type:'truck',location:{kind:'surface',bodyId:'star-47-p9',local:[0,1,0]}};
const output=Nav.locate(truck,galaxy,742,742);
assert.equal(output.status,'SURFACE');
assert.equal(output.worldName,'Lyra-884 k');
assert.equal(output.systemName,'Lyra-884');
assert.equal(output.bodyId,'star-47-p9');
assert.equal(output.world.id,'star-47-p9');
assert.equal(output.system.id,'star-47');
assert.equal(output.world.kind,'planet');
assert.equal(galaxy.allWorlds.some(x=>x===output.world),true);
const snapshot=JSON.stringify(truck);
assert.equal(Nav.locate(truck,galaxy,42,742).status,'SEED_MISMATCH');
assert.equal(Nav.locate({...truck,location:{kind:'surface',bodyId:'star-999-p99',local:[0,1,0]}},galaxy,742,742).status,'UNRESOLVED');
assert.equal(Nav.locate({...truck,location:{kind:'ship',parentId:'ship-main',slot:'starboard-hangar'}},galaxy,742,742).status,'SHIP');
assert.equal(Nav.locate(null,galaxy,742,742).status,'MISSING');
assert.equal(JSON.stringify(truck),snapshot,'locator must not alter saved truck, seed, or cargo');
console.log('PASS real galaxy 742 maps saved star-47-p9 to Lyra-884 k; original truck never moved; different seed denied');
