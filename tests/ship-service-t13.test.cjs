'use strict';
const assert=require('node:assert/strict');
globalThis.StarfallPhysics={SCENE_METERS_PER_UNIT:1000};
const V=require('../src/physics/vehicles.js');
const O=require('../src/physics/outposts.js');
const Ledger=require('../src/physics/power-ledger-t02.js');
const S=require('../src/physics/ship-service-t13.js');
const body={id:'star-0-p0',radius:2000,kind:'planet',landable:true};
const at=x=>[Math.sin(x/body.radius),0,Math.cos(x/body.radius)];
const ship0=V.createStore().get('ship');
const ship={...ship0,state:{...ship0.state,powerEnabled:true,energyJ:20e6}};
const report={draws:{avionics:ship.stats.avionicsW,instruments:ship.stats.instrumentsW},shed:[],generated:{totalW:2000},radiatedW:40};
const rover0=V.createStore().get('rover');
const rv={id:rover0.definition.id,kind:'local-rover',bodyId:body.id,local:at(12),installed:true,busy:false};
assert.equal(S.repair(null).state,'UNDOCKED');
assert.deepEqual(S.repair({state:'LATCHED',targetId:rv.id,kind:rv.kind,bodyId:body.id,receipts:[{id:'historic',observationId:'obs1',sourceId:rv.id}]}).receipts.map(x=>x.id),['historic']);
assert.equal(S.radio({ship,report}).ready,true);
assert.equal(S.radio({ship:{...ship,state:{...ship.state,powerEnabled:false}},report:null}).ready,true,'legacy ship emergency radio still pays real battery');
assert.equal(S.radio({ship,report:{draws:{avionics:0},shed:['avionics']}}).ready,false,'shed bus never provides phantom radio');
assert.equal(S.radio({ship:{...ship,state:{...ship.state,energyJ:0}},report}).ready,false,'dead ship cannot be a free ground tower');
assert.equal(S.radio({ship:{...ship,state:{...ship.state,loads:{...ship.state.loads,avionics:false}}},report}).ready,false);
assert.equal(S.diagnostic({ship,report,state:null,landed:true,bodyId:body.id}).installed.docking,'docking-ship');
const unpowered={...ship,state:{...ship.state,powerEnabled:false}};
assert.throws(()=>S.latch({state:{},ship:unpowered,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:rv,timeS:40}),/enable engineering power/);
assert.throws(()=>S.latch({state:{},ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:2,target:rv,timeS:40}),/velocity/);
assert.throws(()=>S.latch({state:{},ship,landed:false,shipLocal:at(0),body,relativeSpeedMS:0,target:rv,timeS:40}),/landed/);
assert.throws(()=>S.latch({state:{},ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:{...rv,bodyId:'other-world'},timeS:40}),/another world/);
assert.throws(()=>S.latch({state:{},ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:{...rv,local:at(60)},timeS:40}),/range exceeded/);
assert.throws(()=>S.latch({state:{},ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:{...rv,busy:true},timeS:40}),/moving/);
const latched=S.latch({state:{},ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:rv,timeS:40});
assert.equal(latched.state,'LATCHED');
assert.equal(latched.targetId,rv.id);
assert(S.repair(JSON.parse(JSON.stringify(latched))).state==='LATCHED','docking survives save/reload');
assert.throws(()=>S.latch({state:latched,ship,landed:true,shipLocal:at(0),body,relativeSpeedMS:0,target:rv,timeS:41}),/undock/);
const rover={id:rv.id,energyJ:400000,capacityJ:rover0.stats.batteryCapacityJ};
const q=S.cycle({state:latched,ship,shipLocal:at(0),body,target:rv,timeS:100,report,rover});
assert.equal(q.transfer.fromEnergyJ+q.transfer.drawnJ,ship.state.energyJ);
assert.equal(q.transfer.toEnergyJ-rover.energyJ,q.transfer.deliveredJ);
assert(Math.abs(q.transfer.drawnJ-q.transfer.deliveredJ-q.transfer.lossJ)<1e-8,'electric joules conserved with explicit losses');
assert(q.transfer.deliveredJ<q.transfer.drawnJ);
assert.equal(q.state.readyAtS,140);
assert.throws(()=>S.cycle({state:q.state,ship,shipLocal:at(0),body,target:rv,timeS:120,report,rover}),/cooling down/);
assert.throws(()=>S.cycle({state:latched,ship:{...ship,state:{...ship.state,energyJ:1}},shipLocal:at(0),body,target:rv,timeS:150,report,rover}),/reserve|powered unshed avionics/);
assert.throws(()=>S.verifyLatch({state:latched,ship,body,shipLocal:at(100),target:rv}),/overstretched/);
const obs={id:'obs-real-rover-A',bodyId:body.id,sourceAssetId:rv.id,probeId:rv.id,instrument:'thermometer',parameter:'temperatureK',
 value:288.5,unit:'K',location:at(12),timeS:85,uncertainty:1.2};
const data=S.receiveRecord({state:latched,ship,shipLocal:at(0),body,target:rv,observation:obs,atS:150,report});
assert.equal(data.duplicate,false);
assert.equal(data.receipt.sourceId,rv.id);
assert.equal(data.receipt.observationId,obs.id);
assert.equal(data.energyJ,ship.state.energyJ-400);
const duplicate=S.receiveRecord({state:data.state,ship,shipLocal:at(0),body,target:rv,observation:obs,atS:151,report});
assert(duplicate.duplicate);
assert.equal(duplicate.energyJ,ship.state.energyJ,'duplicate does not debit ship twice');
assert.equal(duplicate.state.receipts.length,1);
assert.throws(()=>S.receiveRecord({state:latched,ship,shipLocal:at(0),body,target:rv,observation:{...obs,sourceAssetId:'other',probeId:'other'},atS:150,report}),/source asset/);
assert.throws(()=>S.receiveRecord({state:latched,ship,shipLocal:at(0),body,target:rv,observation:{...obs,bodyId:'other'},atS:150,report}),/source observation/);
const undone=S.undock({state:data.state,timeS:170});
assert.equal(undone.state,'UNDOCKED');assert.equal(undone.targetId,null);
assert.equal(undone.receipts.length,1,'science custody remains after undocking');
assert.throws(()=>S.undock({state:undone,timeS:172}),/no existing dock/);
const battery={id:'battery-solar',kind:'grid-battery',bodyId:body.id,local:at(10),powered:true,connectedSolar:true};
assert.throws(()=>S.latch({state:{},ship,landed:true,shipLocal:at(0),body,target:{...battery,powered:false},timeS:200}),/live wired/);
const shore=S.latch({state:{},ship,landed:true,shipLocal:at(0),body,target:battery,timeS:200});
const source={id:battery.id,energyJ:9000000};
const recharge=S.cycle({state:shore,ship,shipLocal:at(0),body,target:battery,timeS:201,report,source});
assert(recharge.transfer.deliveredJ>0);
assert.equal(recharge.transfer.fromEnergyJ+recharge.transfer.drawnJ,source.energyJ);
assert.equal(recharge.transfer.toEnergyJ-ship.state.energyJ,recharge.transfer.deliveredJ);
assert(recharge.transfer.lossJ>0);
assert.throws(()=>S.receiveRecord({state:shore,ship,shipLocal:at(0),body,target:battery,observation:obs,atS:201,report}),/not a rover/);
console.log('PASS T13 pure ship model: legacy but non-free radio, served load guards, actual docking, range/velocity/planet interlocks, joule-conserving battery and shore, source-owned science receipts, duplicate/old-save recovery');
