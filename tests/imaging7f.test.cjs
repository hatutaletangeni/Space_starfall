'use strict';
const assert=require('node:assert/strict'),M=require('../src/physics/imaging7f.js');
const store=new M.Store(),meta={sourceType:'rover',sourceAssetId:'probe-a',bodyId:'world-1',systemId:'star-1',mode:'forward',resolution:512,timeS:1,position:[0,1,0],bytes:20000,sourceName:'Test mast',caption:'STARFALL',observationRefs:['scan-1']};
const job=store.request('rover','probe-a','forward',512,0);
assert.equal(store.jobs.length,1);store.markDelivered(job.id,.2);store.finishJob(job.id);
let pic=store.put(meta);
assert.equal(pic.status,'stored-local');assert.equal(store.get(pic.id).bodyId,'world-1');
store.queueDownlink(pic.id);
let transmitted=store.tick(1,1,()=>({connected:false,quality:0}),()=>5000);
assert.equal(store.get(pic.id).status,'queued');assert.equal(transmitted.length,0,'Blackout must not deliver');
transmitted=store.tick(2,1,()=>({connected:true,quality:.9,delayS:.2}),()=>10000);
assert(transmitted[0]?.sent>0);assert.notEqual(store.get(pic.id).status,'downlinked');
store.tick(3,10,()=>({connected:true,quality:.9,delayS:.2}),()=>20000);
assert.equal(store.get(pic.id).status,'in-transit');
store.tick(3.3,.3,()=>({connected:true,quality:1}),()=>20000);
assert.equal(store.get(pic.id).status,'downlinked');assert(store.get(pic.id).receivedAtS>=3.3);
const orb=store.put({...meta,sourceType:'satellite',sourceAssetId:'sat-1',mode:'nadir',bytes:40000,timeS:5});
assert(orb.id!==pic.id);assert.equal(orb.sourceType,'satellite');
assert.throws(()=>store.request('rover','probe-a','nadir',128,3));
assert.throws(()=>store.put({...meta,position:[NaN,1,0]}));
assert.throws(()=>store.put({...meta,bytes:3e6}));
assert.throws(()=>store.put({...meta,sourceType:'unknown'}));
assert.deepEqual(new M.Store(store.serialize()).serialize(),store.serialize());
assert.equal(new M.Store({schema:20,photos:[pic]}).photos.length,0);
const bounded=new M.Store();for(let i=0;i<M.MAX_ROVER;i++)bounded.put({...meta,timeS:i});assert.throws(()=>bounded.put(meta),/storage count full/);
const full=new M.Store();for(let i=0;i<Math.min(40,M.MAX_SATELLITE);i++)full.put({...meta,sourceType:'satellite',sourceAssetId:'sat-'+i,mode:'nadir',bytes:1000000,timeS:i});
assert.throws(()=>full.put(meta),/storage byte budget|storage full|storage count full/);
const copy=store.remove(orb.id);assert.equal(copy.id,orb.id);assert(!store.get(orb.id));
console.log('PASS 7F: validated image metadata, onboard queue/blackout, bandwidth-limited downlink, received-on-delay, distinct satellite records, safe load, bounded counts and byte quota');