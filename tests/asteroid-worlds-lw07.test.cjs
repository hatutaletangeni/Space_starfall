'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const engine=fs.readFileSync('src/engine.js','utf8');
const flight=fs.readFileSync('src/flight.js','utf8');
const eventsCss=fs.readFileSync('src/events/events.css','utf8');
const index=fs.readFileSync('index.html','utf8');
const FieldScience=require('../src/physics/science-field.js');
const asteroidFixture={id:'asteroid-test',kind:'asteroid',type:'Rocky',landable:true,atmosphere:'Vacuum',gravity:.002,seed:7};
assert.equal(FieldScience.profile(asteroidFixture,742).pressurePa,0,'Asteroid surfaces must remain vacuum');
assert.equal(FieldScience.sample({body:asteroidFixture,seed:742,local:[1,0,0],altitudeM:.6,instrument:'spectrometer',energyAvailableJ:1000}).quality,'estimated');
assert.ok(engine.includes('function craterRelief('),'Surface crater relief must be a real heightfield');
assert.ok(engine.includes('renderPlanetaryEvent(state,eye,vp,renderH)'),'Weather event particles must render in 3D');
assert.ok(engine.includes('renderAsteroidImpact(state,eye,vp,renderH)'),'Asteroid collision must have a 3D impact effect');
assert.ok(engine.includes('this.eventScratch=new Float32Array(8*256)'),'3D event particles must reuse a bounded typed buffer');
assert.ok(engine.includes('verts=this.eventScratch;let written=0'),'rain, snow and dust must use the reusable 3D particle buffer');
assert.ok(engine.includes('body.impactRevision||0'),'Crater changes must invalidate cached sphere geometry');
assert.ok(!engine.includes("if(planet.type==='Shattered'&&withTerrain)"),'Shattered bodies must not omit surface triangles');
assert.ok(engine.includes("planet.kind==='asteroid'"),'Asteroid-specific stable terrain sampling must exist');
assert.ok(engine.includes("near?.kind==='asteroid'&&rock.id===near.id"),'Selected asteroid must not be double-rendered as debris');
assert.ok(flight.includes('nearestBodyAt(pos)'),'Flight must include asteroid bodies in nearest-surface selection');
assert.ok(flight.includes('asteroidMiningAdvanceLW07(dt)'),'EVA extraction must advance through the bounded simulation loop');
assert.ok(flight.includes('asteroidImpactsLW07:impactsLW07.serialize()'),'Impact crater records must be saved');
assert.ok(flight.includes('asteroidMiningLW07:asteroidMiningLW07.snapshot()'),'EVA pouch and active extraction must be saved');
assert.ok(!eventsCss.includes('repeating-linear-gradient'),'Weather event overlays must not use flat repeated streak lines');
assert.ok(index.includes('src/physics/asteroid-impacts-lw07.js'));
assert.ok(index.includes('src/physics/asteroid-mining-lw07.js'));
assert.ok(index.includes('id="multitool9g-mine"')&&index.includes('id="multitool9g-transfer"'));
console.log('PASS LW07 renderer, flight integration, persistent impact/mining state and event visual regression gates');
