'use strict';
const assert=require('node:assert/strict');
const Mod=require('../src/physics/modular-ship8e.js');
const Walk=require('../src/physics/ship-walk8e.js');
const Bay=require('../src/physics/cargo-bay8b.js');
const Ship=Mod.restore();
assert.equal(Ship.list().length,10);
assert.ok(Ship.mass()>40000,'Large modular vessel structural mass is at least tens of tonnes');
const cargo=Ship.describe('cargo');
assert.equal(cargo.level,1);
assert.equal(cargo.name,'Internal vehicle cargo hold');
assert.equal(Ship.describe('solar',{get:()=>({definition:{slots:{solar:'solar-ship-large'}}})}).engineeringComponent,'solar-ship-large');
assert.ok(cargo.upgradeCost.iron_ore>0);
assert.throws(()=>Ship.upgrade('cargo',{id:'free',module:'cargo',status:'COMMITTED',fromLevel:1,materialsConsumed:{iron_ore:0,aluminum_ore:0}}),/shortfall/);
assert.throws(()=>Ship.upgrade('cargo',null),/receipt/);
const receipt={id:'factory:serial-1',module:'cargo',status:'COMMITTED',fromLevel:1,materialsConsumed:{iron_ore:1300,aluminum_ore:1200}};
const upgraded=Ship.upgrade('cargo',receipt);
assert.equal(upgraded.level,2);
assert.deepEqual(Ship.upgrade('cargo',receipt),upgraded);
assert.throws(()=>Ship.upgrade('solar',{...receipt}),/another module/);
const saved=Ship.snapshot(),restored=Mod.restore(saved);
assert.equal(restored.describe('cargo').level,2);
assert.deepEqual(restored.upgrade('cargo',receipt),upgraded);
assert.throws(()=>Mod.restore({schema:100,levels:{},transactions:[]}),/Unsupported/);
const start=Walk.restore();
assert.ok(Walk.reachable(start.x,start.z));
assert.equal(Walk.room(0,-42),'bridge');
assert.equal(Walk.room(16,5),'cargo');
assert.equal(Walk.room(-17,-24),'science');
assert.ok(!Walk.reachable(100,500));
assert.throws(()=>Walk.move(start,50,0),/Invalid/);
assert.throws(()=>Walk.restore({x:500,z:0,heading:0}),/Corrupt/);
let at={x:0,z:-20};
for(let i=0;i<100;i++)at=Walk.move(at,-.25,0);
assert.equal(Walk.room(at.x,at.z),'science','Rooms have actual continuous access from corridor');
const after=Walk.restore({x:at.x,z:at.z,heading:Math.PI});
assert.deepEqual(Walk.move(after,0,0),{x:after.x,z:after.z});
assert.ok(Bay.BAY.minX>=8,'Cargo loading lane remains same as 8B save-state geometry');
assert.ok(Bay.BAY.maxX<=24,'Integrated hull contains existing vehicle lane');
console.log('8E ship module inventory, no-free-upgrades and connected interior navigation PASS');
