'use strict';
const assert=require('node:assert/strict');
const Inv=require('../src/physics/physical-inventory8a.js');
const base=Inv.create();
const one=base.list().filter(a=>a.type==='truck');
assert.equal(one.length,1,'Exactly one initial truck');
assert.equal(one[0].location.kind,'ship');
assert.equal(base.list().filter(a=>a.type==='science-rover').length,1);
const dir=[0,1,0],a='truck-expedition-001';
const transfer=base.move(a,{kind:'surface',bodyId:'world-A',local:dir},'first-deployment');
assert.equal(transfer.status,'COMMITTED');
assert.equal(base.get(a).location.bodyId,'world-A');
assert.deepEqual(base.move(a,{kind:'surface',bodyId:'world-A',local:dir},'first-deployment'),transfer,'Replay is idempotent');
assert.throws(()=>base.move('rover-science-001',{kind:'surface',bodyId:'world-A',local:dir},'first-deployment'),/already used/);
assert.throws(()=>base.move(a,{kind:'ship',slot:'hold'},'bad-capacity',{maxMassKg:100}),/mass/);
base.setSurface(a,'world-A',[1,0,0],{batteryJ:9e6});
const saved=base.serialize(),reloaded=Inv.create(saved);
assert.equal(reloaded.get(a).location.bodyId,'world-A');
assert.equal(reloaded.get(a).state.batteryJ,9e6);
assert.equal(reloaded.list().length,3);
assert.equal(reloaded.list().filter(x=>x.type==='truck').length,1);
assert.deepEqual(reloaded.move(a,{kind:'surface',bodyId:'world-A',local:dir},'first-deployment'),transfer);
const legacy=Inv.create(null,{truckPose:{bodyId:'old-planet',local:[0,0,1],batteryJ:1234},roverPose:{bodyId:'old-moon',local:[0,1,0]}});
assert.equal(legacy.get(a).location.bodyId,'old-planet');
assert.equal(legacy.get(a).provenance,'legacy_import');
assert.equal(legacy.get('rover-science-001').location.bodyId,'old-moon');
assert.throws(()=>reloaded.move(a,{kind:'surface',bodyId:'other',local:[0,0,0]},'invalid'),/Invalid body-fixed/);
assert.throws(()=>reloaded.move(a,{kind:'ship',slot:'hold'},'first-deployment'),/different asset or destination/);
assert.throws(()=>Inv.create({schema:99,assets:[]}),/Unsupported physical inventory/);
assert.throws(()=>reloaded.move(a,{kind:'ship',slot:'hold'},'wrong-owner',{expected:{kind:'ship',slot:'hold'}}),/Custody changed/);
assert.throws(()=>Inv.create({schema:1,assets:[saved.assets[1],saved.assets[1]]}),/Duplicate physical asset/);
console.log('Update 8A physical custody tests: PASS');
