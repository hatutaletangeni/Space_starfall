/* T11 model tests: real Foundation wiring/90 W bus, launch custody, orbit gate,
 * previously placed pad migration and explicit cross-body trajectory limitations. */
'use strict';
const assert=require('node:assert/strict');
require('../src/physics/rocket-flight7b.js');
require('../src/physics/launch-systems.js');
require('../src/physics/outposts.js');
require('../src/physics/power-ledger-t02.js');
require('../src/physics/rover-lifecycle-t06.js');
require('../src/physics/launch-pad-t11.js');
const X=globalThis.StarfallLaunch,O=globalThis.StarfallOutposts,T=globalThis.StarfallPadT11;
const seed=742,body={id:'star-0-p0',systemId:'star-0',landable:true,gravity:1.24,radius:2150,kind:'planet',position:[0,0,0],spinPeriod:1200};
const at=()=>0,up=[0,1,0],remote={id:'star-1-p0',systemId:'star-1',landable:true,gravity:.4,radius:1400};
const dstSystem={id:'star-1'},localSystem={id:'star-0'};
const design={engine:'atlas',tanks:6,stages:3,boosters:2,payload:'relay'};
const output=new O.Store(seed);
const p=output.add('foundation',body,up,[1,0,0],at).item;
let pad=output.items.find(x=>x.id===p.id);
const batterydir=[.02,Math.sqrt(1-.02*.02),0],b=output.add('battery',body,batterydir,[1,0,0],at).item;
output.link(pad.id,b.id,body);
assert.equal(T.inspect({pad,body,launchStore:new X.Store(seed)}).ready,true,'Legacy pads operate without the new commissioning network');
assert.equal(T.requiredWatts(pad),0);
T.configure(pad,'commissioned',10);
assert.equal(T.requiredWatts(pad),90,'Commissioned pad adds a genuine T02 bus load');
let report=output.power(body,[50000000,0,0],3.8e26,20,10,1000,[],()=>1);
assert.equal(report.byId[pad.id].loadW,90,'Actual group solver supplies pad control electronics');
assert(report.byId[b.id].batteryJ<36e6,'Actual source battery loses energy under commissioning load');
const store=new X.Store(seed);
const ctx=()=>({outposts:output,powerReport:report,heightAt:at});
const check=()=>T.inspect({pad,body,launchStore:store,...ctx()});
assert.equal(check().ready,true,JSON.stringify(check().reasons));
const valid=store.launch({body,foundation:pad,design,time:30,padContext:ctx()});
assert.equal(valid.payloadT11.kind,'relay');assert.equal(valid.payloadT11.massKg,X.PAYLOADS.relay.massKg);
assert.equal(valid.payloadT11.route,'LOCAL_ORBIT');assert.equal(valid.payloadT11.attached,true);
assert.equal(valid.payloadT11.destinationBodyId,body.id);
assert.equal(store.satellites.length,0,'Payload stays on rocket before stable orbit');
assert.throws(()=>store.launch({body,foundation:pad,design,time:31,padContext:ctx()}),/occupied|in use/i);
const restoredOutposts=new O.Store(seed,output.serialize());
assert.equal(restoredOutposts.items.find(x=>x.id===pad.id).padT11.mode,'commissioned');
const saved=store.serialize(),restored=new X.Store(seed,saved);
assert.equal(restored.launches[0].payloadT11.id,valid.payloadT11.id,'Manifest survives migration/restore');
const afterFirst=store.deploy(store.launches[0],31,()=>body);
assert.equal(afterFirst,false,'Cannot deploy on pre-orbit ascent');
assert.equal(store.satellites.length,0);
const noSource=new X.Store(seed);
output.unlink(pad.id,b.id);
report=output.power(body,[50000000,0,0],3.8e26,40,10,1000,[],()=>1);
assert.equal(T.inspect({pad,body,launchStore:noSource,...ctx()}).ready,false);
assert.throws(()=>noSource.launch({body,foundation:pad,design,time:40,padContext:ctx()}),/wired|control/i);
T.configure(pad,'legacy',41);
assert.equal(T.requiredWatts(pad),0);
const old=store.launches[0];assert.throws(()=>T.configure(pad,'commissioned',42,new X.Store(seed,{schema:1,seed,launches:[{...old,phase:'coast'}]})),/active/);
const legacyLaunch=noSource.launch({body,foundation:pad,design,time:41});
assert.equal(legacyLaunch.payloadT11.route,'LOCAL_ORBIT');
assert.throws(()=>new X.Store(seed).launch({body,foundation:pad,design:{...design,payload:'rover'},time:42,
 destinationBody:{...body,id:'star-0-p1'},destinationSystem:localSystem}),/Same-system cross-planet transfer/);
const remoteStore=new X.Store(seed);
const launchRover=remoteStore.launch({body,foundation:pad,design:{...design,payload:'rover'},time:42,
 destinationBody:remote,destinationSystem:dstSystem,landingLocal:[.1,.3,.9]});
assert.equal(launchRover.payloadT11.route,'FICTIONAL_INTERSTELLAR_CARRIER');
assert(Math.abs(Math.hypot(...launchRover.payloadT11.siteLocal)-1)<1e-12);
assert.equal(remoteStore.rovers.length,0);
assert.equal(T.canDeploy(remoteStore.launches[0]).ok,false);
assert.equal(new X.Store(seed,remoteStore.serialize()).launches[0].payloadT11.id,launchRover.payloadT11.id);
// This is a real 7B force-step release, not a fixture that forces orbit/deployment.
const real=new X.Store(seed),rocket=real.launch({body,foundation:pad,design,time:1});
const lookup=id=>id===body.id?body:null;
for(let time=1;time<=1501&&real.launches[0].phase!=='deployed'&&real.launches[0].phase!=='failed';time+=30)real.update(time,lookup);
assert.equal(real.launches[0].phase,'deployed','A real successful physical orbit should release payload via T11');
assert.equal(real.satellites.length,1,'Satellite born only after valid orbital insertion');
assert.equal(real.launches[0].payloadT11.assetId,real.satellites[0].id);
assert.equal(real.satellites[0].payloadT11.launchId,rocket.id);
assert.equal(real.launches[0].payloadT11.attached,false);
console.log('PASS T11: pad commissioning/connected 90W load, launch occupancy, payload custody, deploy orbit guard, stable manifest saves, destination-site normalization and unsupported trajectory rejection');
